    public const string InUse = "IN-USE";

    /// <summary>The SYS/PERM response code.</summary>
    public const string SystemPermanent = "SYS/PERM";

    /// <summary>The SYS/TEMP response code.</summary>
    public const string SystemTemporary = "SYS/TEMP";

    /// <summary>The AUTH response code.</summary>
    public const string Authentication = "AUTH";

    /// <summary>The UTF8 response code.</summary>
    public const string Utf8 = "UTF8";
}
