    // These compact messages are synthetic CC0-1.0 fixtures with reserved-domain
    // data. Their fixed header order, folding, boundaries, and transfer encodings
    // reproduce output shapes from the named public library generators. The Go
    // net/mail package is parser-only, so its case is a documented accepted shape.
    static IEnumerable<TestCaseData> LibraryMessages()
    {
        yield return new TestCaseData("MimeKit", MimeKitMessage(), "mixed", 2, "MimeKit plain body");
        yield return new TestCaseData("Jakarta Mail", JakartaMailMessage(), "mixed", 2, "Jakarta plain body");
        yield return new TestCaseData("Python email", File.ReadAllText(CorpusPath("libraries/python-email-3.9.6.eml")), "alternative", 2, "Plain body generated by Python");
        yield return new TestCaseData("Nodemailer", NodemailerMessage(), "alternative", 2, "Nodemailer plain body");
        yield return new TestCaseData("Apache Mime4j", Mime4jMessage(), "mixed", 2, "Mime4j plain body");
        yield return new TestCaseData("Go net/mail", GoNetMailMessage(), "plain", 0, "Go net/mail body");
        yield return new TestCaseData("Outlook/Exchange", OutlookExchangeMessage(), "alternative", 2, "Exchange plain body");
        yield return new TestCaseData("Gmail", GmailMessage(), "alternative", 2, "Gmail plain body");
    }

    [TestCaseSource(nameof(LibraryMessages))]
    public void ParsesAndExactlyPreservesRepresentativeLibraryWireOutput(string producer, string source, string expectedSubtype, int expectedChildren, string expectedPlainText)
    {
        byte[] input = Encoding.UTF8.GetBytes(source);
        EmailParseResult parsed = new EmailParser().ParseMessageWithInputAndOptionsUsingValueArrayAndEmailParseOptions(input, new EmailParseOptionsOperations().CreatePreserving());

        Assert.That(parsed.IsComplete(), Is.True, producer);
        Assert.That(parsed.IsSuccess(), Is.True, producer);
        Assert.That(parsed.HasMessage(), Is.True, producer);
        EmailMessage message = parsed.GetMessage()!;
        Assert.That(message.GetHeaders()!.GetFirst("From"), Is.Not.Null, producer);
        Assert.That(message.GetBody()!.GetMediaType()!.GetSubtype(), Is.EqualTo(expectedSubtype), producer);
        Assert.That(message.GetBody()!.GetChildCount(), Is.EqualTo(expectedChildren), producer);

        MimeEntity plain = new EmailBodySelector().GetPlainTextWithMessage(message)!;
        string text = new EmailTextProcessor().DecodeWithEntity(plain).GetText();
        Assert.That(text, Does.Contain(expectedPlainText), producer);

        EmailWriteResult preserved = new EmailWriter().WriteMessageWithMessageAndOptions(message, new EmailWriteOptionsOperations().CreateExactPreservation());
        Assert.That(preserved.IsSuccess(), Is.True, producer);
        Assert.That(preserved.GetBytes(), Is.EqualTo(input), producer);
    }

    [Test]
    public void ParsesOpenSslAndGnuPgCompatibleSecurityCorpusAndRejectsFalseEncryption()
    {
        EmailParseResult openSslMessage = ParseCorpus("security/openssl-smime-signed.eml");
        MimeEntity openSslBody = openSslMessage.GetMessage()!.GetBody()!;
        byte[] cms = new EmailDecodedContent().ReadPrefixWithEntityAndMaximumPrefixBytes(openSslBody, 100000);
        EmailCmsReadResult cmsResult = new EmailCmsReader().ParseWithInputUsingReadOnlySpan(cms);
        EmailSmimeVerificationOptions verificationOptions = new EmailSmimeVerificationOptions();
        verificationOptions.SetVerifyCertificateChain(false);
        EmailSmimeVerificationResult openSslVerification = new EmailSmimeVerifier().VerifyOpaqueWithCmsAndOptions(cms, verificationOptions);

        EmailParseResult gnuPgCompatible = ParseCorpus("security/synthetic-pgp-mime.eml");
        MimeEntity pgpRoot = gnuPgCompatible.GetMessage()!.GetBody()!;
        EmailSecurityMultipartParseResult framing = new EmailSecurityMultipartParser().ParseWithRoot(pgpRoot);
        byte[] armored = new EmailDecodedContent().ReadPrefixWithEntityAndMaximumPrefixBytes(pgpRoot.GetChildAt(1), 100000);
        EmailOpenPgpReadResult packets = new EmailOpenPgpReader().ParseWithInput(armored);
        EmailOpenPgpDecryptionResult rejected = new EmailOpenPgpMimeDecryptor().DecryptWithRootAndCredentials(pgpRoot, new List<EmailOpenPgpDecryptionCredential>());

        Assert.That(openSslMessage.IsSuccess(), Is.True);
        Assert.That(cmsResult.IsSuccess(), Is.True);
        Assert.That(cmsResult.GetContentInfo()!.GetContentKind(), Is.EqualTo(EmailCmsContentKind.SignedData));
        Assert.That(openSslVerification.GetSignerAt(0).GetStatus(), Is.EqualTo(EmailSmimeSignerVerificationStatus.CertificateNotFound));
        Assert.That(framing.IsRecognized(), Is.True);
        Assert.That(framing.IsSuccess(), Is.False);
        Assert.That(framing.GetIssues().ContainsCode(EmailIssueCode.SecurityMultipartStructureMalformed), Is.True);
        Assert.That(framing.GetSecurityMultipart()!.GetProtocol(), Is.EqualTo("application/pgp-encrypted"));
        Assert.That(packets.IsSuccess(), Is.True);
        Assert.That(packets.GetPacketAt(0).GetKind(), Is.EqualTo(EmailOpenPgpPacketKind.LiteralData));
        Assert.That(rejected.GetStatus(), Is.EqualTo(EmailOpenPgpDecryptionStatus.Malformed));
        Assert.That(rejected.HasContent(), Is.False);
    }

    [Test]
    public void StandardsCorpusParsesAndRoundTripsWithoutLibrarySpecificRecovery()
    {
        string[] relativePaths =
        [
            "standards/rfc5322-canonical.eml",
            "standards/rfc2046-nested-multipart.eml",
            "international/rfc2231-filename.eml",
            "international/smtputf8-message.eml"
        ];

        foreach (string relativePath in relativePaths)
        {
            byte[] input = File.ReadAllBytes(CorpusPath(relativePath));
            EmailParseResult parsed = new EmailParser().ParseMessageWithInputAndOptionsUsingValueArrayAndEmailParseOptions(input, new EmailParseOptionsOperations().CreatePreserving());
            EmailWriteResult written = new EmailWriter().WriteMessageWithMessageAndOptions(parsed.GetMessage()!, new EmailWriteOptionsOperations().CreateExactPreservation());

            Assert.That(parsed.IsComplete(), Is.True, relativePath);
            Assert.That(parsed.IsSuccess(), Is.True, relativePath);
            Assert.That(written.GetBytes(), Is.EqualTo(input), relativePath);
        }
    }

    [TestCase("Exchange", "X-MS-Exchange-Organization-MessageDirectionality: Originating", EmailIssueCode.ExchangeCompatibilityRecovery)]
    [TestCase("Gmail", "X-Google-Original-From: sender@example.test", EmailIssueCode.GmailCompatibilityRecovery)]
    public void ProviderSpecificBrokenBoundariesRequireExplicitCompatibilityPolicy(string producer, string providerHeader, EmailIssueCode expectedIssue)
    {
        string source = providerHeader + "\r\nContent-Type: multipart/mixed; boundary=provider-boundary\r\n\r\n"
            + "--\"provider-boundary\"\r\nContent-Type: text/plain\r\n\r\nbody\r\n--\"provider-boundary\"--\r\n";
        EmailParseOptions disabledOptions = ProviderOptions(false, expectedIssue);
        EmailParseOptions enabledOptions = ProviderOptions(true, expectedIssue);

        EmailParseResult disabled = new EmailParser().ParseMessageWithInputAndOptionsUsingValueArrayAndEmailParseOptions(Encoding.ASCII.GetBytes(source), disabledOptions);
        EmailParseResult enabled = new EmailParser().ParseMessageWithInputAndOptionsUsingValueArrayAndEmailParseOptions(Encoding.ASCII.GetBytes(source), enabledOptions);
        EmailParseResult strict = new EmailParser().ParseMessageWithInputAndOptionsUsingValueArrayAndEmailParseOptions(Encoding.ASCII.GetBytes(source), new EmailParseOptionsOperations().CreateStrict());

        Assert.That(disabled.GetMessage()!.GetBody()!.GetChildCount(), Is.Zero, producer);
        Assert.That(enabled.GetMessage()!.GetBody()!.GetChildCount(), Is.EqualTo(1), producer);
        Assert.That(enabled.GetIssues().ContainsCode(expectedIssue), Is.True, producer);
        Assert.That(strict.IsSuccess(), Is.False, producer);
    }

    static EmailParseOptions ProviderOptions(bool enabled, EmailIssueCode issue)
    {
        EmailParseOptions options = new EmailParseOptionsOperations().CreateConformingTolerant();
        EmailCompatibilityOptions compatibility = options.GetCompatibilityOptions();
        compatibility.SetAllowBrokenMimeBoundaries(false);
        compatibility.SetAllowExchangeDeviations(enabled && issue == EmailIssueCode.ExchangeCompatibilityRecovery);
        compatibility.SetAllowGmailDeviations(enabled && issue == EmailIssueCode.GmailCompatibilityRecovery);
        options.SetCompatibilityOptions(compatibility);
        return options;
    }

    static EmailParseResult ParseCorpus(string relativePath)
    {
        EmailParseResult result = new EmailParser().ParseMessageWithInputAndOptionsUsingValueArrayAndEmailParseOptions(File.ReadAllBytes(CorpusPath(relativePath)), new EmailParseOptionsOperations().CreatePreserving());
        Assert.That(result.IsComplete(), Is.True, relativePath);
        return result;
    }

    static string CorpusPath(string relativePath)
    {
        return Path.GetFullPath(Path.Combine(TestContext.CurrentContext.TestDirectory, "../../../corpus", relativePath));
    }

