using System;

namespace email;
/// <summary>
/// Defines the public operations implemented by <see cref = "EmailWriteResult"/>.
/// </summary>
public interface IEmailWriteResultContract
{
    /// <summary>
    /// Gets the mode.
    /// </summary>
    /// <returns>The current mode.</returns>
    EmailWriteMode GetMode();
    /// <summary>
    /// Gets the bytes.
    /// </summary>
    /// <remarks>
    /// Collection and array results should be treated as snapshots unless the owning type explicitly documents shared mutable state.
    /// </remarks>
    /// <returns>The current bytes.</returns>
    byte[] GetBytes();
    /// <summary>
    /// Gets the byte count.
    /// </summary>
    /// <returns>The current byte count.</returns>
    int GetByteCount();
    /// <summary>
    /// Gets the issues.
    /// </summary>
    /// <returns>The current issues.</returns>
    EmailIssueList GetIssues();
    /// <summary>
    /// Gets the source byte count.
    /// </summary>
    /// <returns>The current source byte count.</returns>
    long GetSourceByteCount();
    /// <summary>
    /// Gets the copied byte count.
    /// </summary>
    /// <returns>The current copied byte count.</returns>
    long GetCopiedByteCount();
    /// <summary>
    /// Gets the regenerated byte count.
    /// </summary>
    /// <returns>The current regenerated byte count.</returns>
    long GetRegeneratedByteCount();
    /// <summary>
    /// Gets the copied range count.
    /// </summary>
    /// <returns>The current copied range count.</returns>
    int GetCopiedRangeCount();
    /// <summary>
    /// Gets the regenerated range count.
    /// </summary>
    /// <returns>The current regenerated range count.</returns>
    int GetRegeneratedRangeCount();
    /// <summary>
    /// Determines whether the current value or state is success.
    /// </summary>
    /// <returns><c>true</c> when the value or state is success; otherwise, <c>false</c>.</returns>
    bool IsSuccess();
    /// <summary>
    /// Determines whether the fatal error is present or available.
    /// </summary>
    /// <returns><c>true</c> when the fatal error is available; otherwise, <c>false</c>.</returns>
    bool HasFatalError();
}
