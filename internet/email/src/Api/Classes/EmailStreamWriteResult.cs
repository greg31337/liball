using System;

namespace email;
/// <summary>
/// Describes the outcome of a stream write operation.
/// </summary>
/// <remarks>
/// Inspect presence, status, or success methods when available before consuming optional output. A successful or partial result can still include warnings and informational issues.
/// </remarks>
public class EmailStreamWriteResult : IEmailStreamWriteResultContract
{
    EmailWriteMode mode;
    EmailIssueList issues;
    long outputByteCount;
    long sourceByteCount;
    long copiedByteCount;
    long regeneratedByteCount;
    int copiedRangeCount;
    int regeneratedRangeCount;
    /// <summary>
    /// Creates a new stream write result.
    /// </summary>
    /// <param name = "mode">The mode used by the operation.</param>
    /// <param name = "issues">The ordered diagnostics associated with the operation.</param>
    /// <param name = "outputByteCount">The number of items or bytes to process.</param>
    /// <param name = "sourceByteCount">The number of items or bytes to process.</param>
    /// <param name = "copiedByteCount">The number of items or bytes to process.</param>
    /// <param name = "regeneratedByteCount">The number of items or bytes to process.</param>
    /// <param name = "copiedRangeCount">The number of items or bytes to process.</param>
    /// <param name = "regeneratedRangeCount">The number of items or bytes to process.</param>
    /// <exception cref = "ArgumentException">Thrown when an argument is empty, malformed, or inconsistent with the other inputs.</exception>
    /// <exception cref = "ArgumentNullException">Thrown when a required reference argument is null.</exception>
    /// <exception cref = "ArgumentOutOfRangeException">Thrown when a numeric, index, or enum argument is outside the supported range.</exception>
    public EmailStreamWriteResult(EmailWriteMode mode, EmailIssueList issues, long outputByteCount, long sourceByteCount, long copiedByteCount, long regeneratedByteCount, int copiedRangeCount, int regeneratedRangeCount)
    {
        if (mode < EmailWriteMode.ExactPreservation || mode > EmailWriteMode.Canonical)
        {
            throw new ArgumentOutOfRangeException("mode");
        }

        if (issues == null)
        {
            throw new ArgumentNullException("issues");
        }

        if (outputByteCount < 0 || sourceByteCount < 0 || copiedByteCount < 0 || regeneratedByteCount < 0 || copiedRangeCount < 0 || regeneratedRangeCount < 0)
        {
            throw new ArgumentOutOfRangeException("outputByteCount");
        }

        if (copiedByteCount + regeneratedByteCount != outputByteCount)
        {
            throw new ArgumentException("Copied and regenerated byte counts must describe the complete streamed output.", "copiedByteCount");
        }

        this.mode = mode;
        this.issues = new EmailIssueList();
        this.issues.AddRange(issues);
        this.outputByteCount = outputByteCount;
        this.sourceByteCount = sourceByteCount;
        this.copiedByteCount = copiedByteCount;
        this.regeneratedByteCount = regeneratedByteCount;
        this.copiedRangeCount = copiedRangeCount;
        this.regeneratedRangeCount = regeneratedRangeCount;
    }

    /// <summary>
    /// Gets the mode.
    /// </summary>
    /// <returns>The current mode.</returns>
    public EmailWriteMode GetMode()
    {
        return mode;
    }

    /// <summary>
    /// Gets the issues.
    /// </summary>
    /// <returns>The current issues.</returns>
    public EmailIssueList GetIssues()
    {
        EmailIssueList copy = new EmailIssueList();
        copy.AddRange(issues);
        return copy;
    }

    /// <summary>
    /// Gets the output byte count.
    /// </summary>
    /// <returns>The current output byte count.</returns>
    public long GetOutputByteCount()
    {
        return outputByteCount;
    }

    /// <summary>
    /// Gets the source byte count.
    /// </summary>
    /// <returns>The current source byte count.</returns>
    public long GetSourceByteCount()
    {
        return sourceByteCount;
    }

    /// <summary>
    /// Gets the copied byte count.
    /// </summary>
    /// <returns>The current copied byte count.</returns>
    public long GetCopiedByteCount()
    {
        return copiedByteCount;
    }

    /// <summary>
    /// Gets the regenerated byte count.
    /// </summary>
    /// <returns>The current regenerated byte count.</returns>
    public long GetRegeneratedByteCount()
    {
        return regeneratedByteCount;
    }

    /// <summary>
    /// Gets the copied range count.
    /// </summary>
    /// <returns>The current copied range count.</returns>
    public int GetCopiedRangeCount()
    {
        return copiedRangeCount;
    }

    /// <summary>
    /// Gets the regenerated range count.
    /// </summary>
    /// <returns>The current regenerated range count.</returns>
    public int GetRegeneratedRangeCount()
    {
        return regeneratedRangeCount;
    }

    /// <summary>
    /// Determines whether the current value or state is success.
    /// </summary>
    /// <returns><c>true</c> when the value or state is success; otherwise, <c>false</c>.</returns>
    public bool IsSuccess()
    {
        return !issues.HasSeverityAtLeast(EmailIssueSeverity.Error);
    }

    /// <summary>
    /// Determines whether the fatal error is present or available.
    /// </summary>
    /// <returns><c>true</c> when the fatal error is available; otherwise, <c>false</c>.</returns>
    public bool HasFatalError()
    {
        return issues.HasSeverityAtLeast(EmailIssueSeverity.Fatal);
    }
}
