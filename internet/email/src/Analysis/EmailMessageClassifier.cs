using System;
using System.Collections.Generic;

namespace email;
internal class EmailMessageClassifierWorker
{
    EmailMessage message;
    EmailMessageClassificationOptions options;
    List<EmailMessageClassificationReason> automated;
    List<EmailMessageClassificationReason> mailingList;
    List<EmailMessageClassificationReason> bounce;
    List<EmailMessageClassificationReason> receipt;

    internal EmailMessageClassifierWorker(EmailMessage message, EmailMessageClassificationOptions options)
    {
        this.message = message;
        this.options = options;
        automated = new List<EmailMessageClassificationReason>();
        mailingList = new List<EmailMessageClassificationReason>();
        bounce = new List<EmailMessageClassificationReason>();
        receipt = new List<EmailMessageClassificationReason>();
    }

    internal EmailMessageClassification Classify()
    {
        ClassifyHeaders();
        ClassifyMimeBody();
        List<EmailMessageClassificationResult> results = new List<EmailMessageClassificationResult>();
        results.Add(CreateResult(EmailMessageClassificationKind.Automated, automated));
        results.Add(CreateResult(EmailMessageClassificationKind.MailingList, mailingList));
        results.Add(CreateResult(EmailMessageClassificationKind.Bounce, bounce));
        results.Add(CreateResult(EmailMessageClassificationKind.Receipt, receipt));
        return new EmailMessageClassification(results);
    }

    void ClassifyHeaders()
    {
        EmailHeaders? headers = message.GetHeaders();
        if ((headers ?? throw new InvalidOperationException()).GetCount() > options.GetMaximumHeaderCount()) throw new EmailLimitException("MaxClassificationHeaders", options.GetMaximumHeaderCount(), headers.GetCount());
        ClassifyAutoSubmitted(headers);
        ClassifyListHeaders(headers);
        ClassifyReceiptRequest(headers);
        ClassifyNullReturnPath(headers);
        ClassifyPrecedence(headers);
        ClassifySubject(headers);
    }

    void ClassifyAutoSubmitted(EmailHeaders headers)
    {
        List<EmailHeader> fields = headers.GetAllNamed("Auto-Submitted");
        int index = 0;
        while (index < fields.Count)
        {
            EmailHeader field = fields[index];
            byte[] bytes = GetBoundedValue(field);
            EmailMetadataParserOptions parserOptions = new EmailMetadataParserOptions();
            parserOptions.SetMode(EmailStructuredValueParseMode.Tolerant);
            parserOptions.SetMaximumInputBytes(options.GetMaximumHeaderValueBytes());
            EmailMetadataParseResult parsed = new EmailMetadataParser().ParseAutoSubmittedWithInputAndOptionsAndInitialPosition(bytes, parserOptions, field.GetValueSourcePosition());
            EmailAutoSubmitted? value = parsed.GetAutoSubmitted();
            bool malformed = value == null || parsed.GetIssues().GetCount() > 0 || !parsed.IsComplete();
            if (value == null)
            {
                Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.AutoSubmittedMalformed, EmailMessageClassificationEvidenceStrength.Weak, EmailMessageClassificationEvidenceEffect.Contradicts, "Auto-Submitted is malformed and cannot establish automatic generation.", "RFC 3834 section 5", "Auto-Submitted");
            }
            else if (value.GetKind() == EmailAutoSubmittedKind.AutoGenerated)
            {
                Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.AutoSubmittedGenerated, malformed ? EmailMessageClassificationEvidenceStrength.Moderate : EmailMessageClassificationEvidenceStrength.Strong, EmailMessageClassificationEvidenceEffect.Supports, "Auto-Submitted declares that an automatic process generated the message.", "RFC 3834 section 5.2", "Auto-Submitted");
            }
            else if (value.GetKind() == EmailAutoSubmittedKind.AutoReplied)
            {
                Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.AutoSubmittedReplied, malformed ? EmailMessageClassificationEvidenceStrength.Moderate : EmailMessageClassificationEvidenceStrength.Strong, EmailMessageClassificationEvidenceEffect.Supports, "Auto-Submitted declares that an automatic process replied to another message.", "RFC 3834 section 5.2", "Auto-Submitted");
            }
            else if (value.GetKind() == EmailAutoSubmittedKind.Extension)
            {
                Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.AutoSubmittedExtension, EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Supports, "Auto-Submitted uses a registered or private extension disposition rather than 'no'.", "RFC 3834 section 5.2", "Auto-Submitted");
            }
            else
            {
                Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.AutoSubmittedNo, EmailMessageClassificationEvidenceStrength.Strong, EmailMessageClassificationEvidenceEffect.Contradicts, "Auto-Submitted explicitly declares that the message was not automatically submitted.", "RFC 3834 section 5.2", "Auto-Submitted");
            }

            if (value != null && malformed)
            {
                Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.AutoSubmittedMalformed, EmailMessageClassificationEvidenceStrength.Weak, EmailMessageClassificationEvidenceEffect.Contradicts, "Auto-Submitted contains recoverable syntax defects, so its supporting disposition was downgraded.", "RFC 3834 section 5.1", "Auto-Submitted");
            }

            index++;
        }

        if (fields.Count > 1)
        {
            Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.AutoSubmittedMalformed, EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Contradicts, "More than one Auto-Submitted field is present although the field is a singleton.", "RFC 3834 section 5.1", "Auto-Submitted");
        }
    }

    void ClassifyListHeaders(EmailHeaders headers)
    {
        List<EmailHeader> identifiers = headers.GetAllNamed("List-Id");
        int validIdentifiers = 0;
        int malformedIdentifiers = 0;
        int index = 0;
        while (index < identifiers.Count)
        {
            byte[] bytes = GetBoundedValue(identifiers[index]);
            if (IsValidListIdentifier(bytes)) validIdentifiers++;
            else malformedIdentifiers++;
            index++;
        }

        if (validIdentifiers > 0)
        {
            Add(EmailMessageClassificationKind.MailingList, EmailMessageClassificationReasonCode.ListIdentifier, identifiers.Count == 1 ? EmailMessageClassificationEvidenceStrength.Strong : EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Supports, "A syntactically valid List-Id identifies the distribution list that emitted the message.", "RFC 2919 sections 2-3", "List-Id");
        }

        if (malformedIdentifiers > 0)
        {
            Add(EmailMessageClassificationKind.MailingList, EmailMessageClassificationReasonCode.ListIdentifierMalformed, EmailMessageClassificationEvidenceStrength.Weak, EmailMessageClassificationEvidenceEffect.Contradicts, "A List-Id field is present but does not satisfy the standardized list identifier syntax.", "RFC 2919 sections 2-3", "List-Id");
        }

        if (identifiers.Count > 1)
        {
            Add(EmailMessageClassificationKind.MailingList, EmailMessageClassificationReasonCode.ListIdentifierDuplicated, EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Contradicts, "List-Id is duplicated although only one field is permitted in a message.", "RFC 2919 section 3", "List-Id");
        }

        int validManagement = 0;
        int malformedManagement = 0;
        string[] names = new string[] { "List-Help", "List-Unsubscribe", "List-Subscribe", "List-Post", "List-Owner", "List-Archive" };
        index = 0;
        while (index < names.Length)
        {
            List<EmailHeader> fields = headers.GetAllNamed(names[index]);
            int fieldIndex = 0;
            while (fieldIndex < fields.Count)
            {
                EmailHeader field = fields[fieldIndex];
                byte[] bytes = GetBoundedValue(field);
                EmailMetadataParserOptions parserOptions = new EmailMetadataParserOptions();
                parserOptions.SetMode(EmailStructuredValueParseMode.Tolerant);
                parserOptions.SetMaximumInputBytes(options.GetMaximumHeaderValueBytes());
                EmailMetadataParseResult parsed = new EmailMetadataParser().ParseListManagementWithInputAndKindAndOptionsAndInitialPosition(bytes, GetListKind(names[index]), parserOptions, field.GetValueSourcePosition());
                if (parsed.HasValue() && parsed.GetIssues().GetCount() == 0 && parsed.IsComplete()) validManagement++;
                else malformedManagement++;
                fieldIndex++;
            }

            index++;
        }

        List<EmailHeader> oneClickFields = headers.GetAllNamed("List-Unsubscribe-Post");
        index = 0;
        while (index < oneClickFields.Count)
        {
            EmailHeader field = oneClickFields[index];
            byte[] bytes = GetBoundedValue(field);
            EmailMetadataParserOptions parserOptions = new EmailMetadataParserOptions();
            parserOptions.SetMode(EmailStructuredValueParseMode.Tolerant);
            parserOptions.SetMaximumInputBytes(options.GetMaximumHeaderValueBytes());
            EmailMetadataParseResult parsed = new EmailMetadataParser().ParseListUnsubscribePostWithInputAndOptionsAndInitialPosition(bytes, parserOptions, field.GetValueSourcePosition());
            if (parsed.HasValue() && parsed.GetIssues().GetCount() == 0 && parsed.IsComplete()) validManagement++;
            else malformedManagement++;
            index++;
        }

        if (validManagement > 0)
        {
            Add(EmailMessageClassificationKind.MailingList, EmailMessageClassificationReasonCode.ListManagementHeader, EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Supports, "One or more valid List-* management fields provide list command metadata.", "RFC 2369 and RFC 8058", "List-*");
        }

        if (malformedManagement > 0)
        {
            Add(EmailMessageClassificationKind.MailingList, EmailMessageClassificationReasonCode.ListManagementHeaderMalformed, EmailMessageClassificationEvidenceStrength.Weak, EmailMessageClassificationEvidenceEffect.Supports, "List-* management fields are present but malformed; their names provide only weak list evidence.", "RFC 2369 and RFC 8058", "List-*");
        }
    }

    void ClassifyReceiptRequest(EmailHeaders headers)
    {
        if (!headers.Contains("Disposition-Notification-To")) return;
        EmailDispositionNotificationRequestParseResult request = new EmailDispositionNotificationParser().ParseRequestWithMessageAndMode(message, EmailStructuredValueParseMode.Tolerant);
        Add(EmailMessageClassificationKind.Receipt, EmailMessageClassificationReasonCode.DispositionNotificationRequest, request.HasRequest() ? EmailMessageClassificationEvidenceStrength.Strong : EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Contradicts, "Disposition-Notification-To requests a future MDN; it is not evidence that this message is itself a receipt.", "RFC 8098 section 2.1", "Disposition-Notification-To");
    }

    void ClassifyNullReturnPath(EmailHeaders headers)
    {
        List<EmailHeader> fields = headers.GetAllNamed("Return-Path");
        int index = 0;
        while (index < fields.Count)
        {
            string value = (GetBoundedText(fields[index]) ?? throw new InvalidOperationException()).Trim();
            if (string.Equals(value, "<>", StringComparison.Ordinal))
            {
                Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.NullReturnPath, EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Supports, "The trace Return-Path records a null reverse-path, as required for delivery notifications and other non-replyable service messages.", "RFC 5321 section 4.4", "Return-Path");
                Add(EmailMessageClassificationKind.Bounce, EmailMessageClassificationReasonCode.NullReturnPath, EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Supports, "A null reverse-path is required for delivery notifications, but does not by itself prove a delivery failure.", "RFC 5321 section 4.4", "Return-Path");
                return;
            }

            index++;
        }
    }

    void ClassifyPrecedence(EmailHeaders headers)
    {
        List<EmailHeader> fields = headers.GetAllNamed("Precedence");
        int index = 0;
        while (index < fields.Count)
        {
            string value = (GetBoundedText(fields[index]) ?? throw new InvalidOperationException()).Trim();
            if (string.Equals(value, "list", StringComparison.OrdinalIgnoreCase))
            {
                Add(EmailMessageClassificationKind.MailingList, EmailMessageClassificationReasonCode.PrecedenceList, EmailMessageClassificationEvidenceStrength.Weak, EmailMessageClassificationEvidenceEffect.Supports, "The non-standard Precedence value 'list' is a legacy mailing-list convention.", "Non-standard Precedence convention", "Precedence");
            }
            else if (string.Equals(value, "bulk", StringComparison.OrdinalIgnoreCase))
            {
                Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.PrecedenceBulk, EmailMessageClassificationEvidenceStrength.Weak, EmailMessageClassificationEvidenceEffect.Supports, "The non-standard Precedence value 'bulk' is weak legacy evidence of automated bulk submission.", "Non-standard Precedence convention", "Precedence");
            }

            index++;
        }
    }

    void ClassifySubject(EmailHeaders headers)
    {
        EmailHeader? field = headers.GetFirst("Subject");
        if (field == null) return;
        string? subject = GetBoundedText(field);
        if ((subject ?? throw new InvalidOperationException()).Length > options.GetMaximumSubjectCharacters()) subject = subject.Substring(0, options.GetMaximumSubjectCharacters());
        string normalized = subject.ToLowerInvariant();
        if (ContainsAny(normalized, new string[] { "delivery status notification", "undeliverable", "mail delivery failed", "failure notice", "returned mail" }))
        {
            Add(EmailMessageClassificationKind.Bounce, EmailMessageClassificationReasonCode.BounceSubject, EmailMessageClassificationEvidenceStrength.Weak, EmailMessageClassificationEvidenceEffect.Supports, "The subject resembles common delivery-failure wording, which is not standardized and may be spoofed or localized.", "Heuristic subject evidence; not an Internet standard", "Subject");
        }

        if (ContainsAny(normalized, new string[] { "read receipt", "return receipt", "disposition notification", "delivery receipt" }))
        {
            Add(EmailMessageClassificationKind.Receipt, EmailMessageClassificationReasonCode.ReceiptSubject, EmailMessageClassificationEvidenceStrength.Weak, EmailMessageClassificationEvidenceEffect.Supports, "The subject resembles common receipt wording, which is not standardized and may be spoofed or localized.", "Heuristic subject evidence; not an Internet standard", "Subject");
        }
    }

    void ClassifyMimeBody()
    {
        if (!message.HasBody()) return;
        MimeEntity? root = message.GetBody();
        if (((root ?? throw new InvalidOperationException()).GetMediaType() ?? throw new InvalidOperationException()).IsType("multipart", "report")) ClassifyMultipartReport(root);
        List<MimeEntity> entities = new EmailTraversal().DepthFirstWithRootAndMaximumDepthAndMaximumEntityCount(root, options.GetMaximumDepth(), options.GetMaximumEntityCount());
        bool deliveryPart = false;
        bool dispositionPart = false;
        int index = 0;
        while (index < entities.Count)
        {
            EmailMediaType? type = entities[index].GetMediaType();
            if ((type ?? throw new InvalidOperationException()).IsType("message", "delivery-status") || type.IsType("message", "global-delivery-status")) deliveryPart = true;
            if (type.IsType("message", "disposition-notification") || type.IsType("message", "global-disposition-notification")) dispositionPart = true;
            index++;
        }

        if (deliveryPart)
        {
            Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.MachineDeliveryStatusPart, EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Supports, "The MIME tree contains a standardized machine-readable delivery-status part.", "RFC 3464 and RFC 6533", "Content-Type");
        }

        if (dispositionPart)
        {
            Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.MachineDispositionNotificationPart, EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Supports, "The MIME tree contains a standardized machine-readable disposition-notification part.", "RFC 8098 section 3", "Content-Type");
            Add(EmailMessageClassificationKind.Receipt, EmailMessageClassificationReasonCode.MachineDispositionNotificationPart, EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Supports, "A machine-readable disposition-notification part is structural receipt evidence even outside a conforming multipart/report wrapper.", "RFC 8098 section 3", "Content-Type");
        }
    }

    void ClassifyMultipartReport(MimeEntity root)
    {
        EmailReportParseOptions reportOptions = options.GetReportParseOptions();
        EmailReportParseResult parsed = new EmailReportParser().ParseWithRootAndOptions(root, reportOptions);
        if (!parsed.HasReport()) return;
        EmailMultipartReport? report = parsed.GetReport();
        if ((report ?? throw new InvalidOperationException()).IsDeliveryStatus())
        {
            Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.DeliveryStatusReport, EmailMessageClassificationEvidenceStrength.Strong, EmailMessageClassificationEvidenceEffect.Supports, "The message is a standardized multipart delivery status notification.", "RFC 3464", "Content-Type");
            ClassifyDeliveryStatus(root, reportOptions);
        }
        else if (report.IsDispositionNotification())
        {
            EmailDispositionNotificationParseResult notification = new EmailDispositionNotificationParser().ParseWithRootAndOptions(root, reportOptions);
            Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.DispositionNotificationReport, notification.HasNotification() ? EmailMessageClassificationEvidenceStrength.Strong : EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Supports, "The message declares the standardized MDN report format.", "RFC 8098 section 3", "Content-Type");
            Add(EmailMessageClassificationKind.Receipt, notification.HasNotification() ? EmailMessageClassificationReasonCode.DispositionNotificationReport : EmailMessageClassificationReasonCode.DispositionNotificationMalformed, notification.HasNotification() ? EmailMessageClassificationEvidenceStrength.Strong : EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Supports, notification.HasNotification() ? "A parsed message disposition notification reports handling of a delivered message." : "The message declares an MDN but its machine-readable fields are malformed.", "RFC 8098 section 3", "Content-Type");
        }
        else if (report.IsFeedbackReport())
        {
            EmailFeedbackReportParseResult feedback = new EmailFeedbackReportParser().ParseWithRootAndOptions(root, reportOptions);
            Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.FeedbackReport, feedback.HasFeedbackReport() ? EmailMessageClassificationEvidenceStrength.Strong : EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Supports, feedback.HasFeedbackReport() ? "The message is a parsed abuse feedback report." : "The message declares an abuse feedback report but contains malformed report fields.", "RFC 5965", "Content-Type");
        }
        else
        {
            Add(EmailMessageClassificationKind.Automated, EmailMessageClassificationReasonCode.MultipartReport, EmailMessageClassificationEvidenceStrength.Moderate, EmailMessageClassificationEvidenceEffect.Supports, "The message uses the standardized multipart/report framework with an unrecognized report type.", "RFC 3462", "Content-Type");
        }
    }

    void ClassifyDeliveryStatus(MimeEntity root, EmailReportParseOptions reportOptions)
    {
        EmailDeliveryStatusParseResult parsed = new EmailDeliveryStatusParser().ParseWithRootAndOptions(root, reportOptions);
        if (!parsed.HasDeliveryStatus())
        {
            Add(EmailMessageClassificationKind.Bounce, EmailMessageClassificationReasonCode.DeliveryStatusMalformed, EmailMessageClassificationEvidenceStrength.Weak, EmailMessageClassificationEvidenceEffect.Supports, "The message declares a DSN, but malformed fields prevent determining whether delivery failed or succeeded.", "RFC 3464", "Content-Type");
            return;
        }

        EmailDeliveryStatus? status = parsed.GetDeliveryStatus();
        bool failed = false;
        bool delayed = false;
        bool successful = false;
        int index = 0;
        while (index < (status ?? throw new InvalidOperationException()).GetRecipientCount())
        {
            EmailDeliveryStatusAction action = status.GetRecipientAt(index).GetAction();
            if (action == EmailDeliveryStatusAction.Failed) failed = true;
            else if (action == EmailDeliveryStatusAction.Delayed) delayed = true;
            else if (action == EmailDeliveryStatusAction.Delivered || action == EmailDeliveryStatusAction.Relayed || action == EmailDeliveryStatusAction.Expanded) successful = true;
            index++;
        }

        if (failed)
        {
            Add(EmailMessageClassificationKind.Bounce, EmailMessageClassificationReasonCode.DeliveryStatusFailure, EmailMessageClassificationEvidenceStrength.Strong, EmailMessageClassificationEvidenceEffect.Supports, "At least one DSN recipient block has Action 'failed', meaning delivery was abandoned.", "RFC 3464 section 2.3.3", "Action");
        }

        if (delayed)
        {
            Add(EmailMessageClassificationKind.Bounce, EmailMessageClassificationReasonCode.DeliveryStatusDelay, EmailMessageClassificationEvidenceStrength.Strong, EmailMessageClassificationEvidenceEffect.Supports, "At least one DSN recipient block has Action 'delayed', meaning delivery has not yet succeeded.", "RFC 3464 section 2.3.3", "Action");
        }

        if (successful)
        {
            Add(EmailMessageClassificationKind.Receipt, EmailMessageClassificationReasonCode.DeliveryStatusSuccess, EmailMessageClassificationEvidenceStrength.Strong, EmailMessageClassificationEvidenceEffect.Supports, "At least one DSN recipient block reports delivered, relayed, or expanded delivery.", "RFC 3464 section 2.3.3", "Action");
        }

        if (!failed && !delayed && !successful)
        {
            Add(EmailMessageClassificationKind.Bounce, EmailMessageClassificationReasonCode.DeliveryStatusMalformed, EmailMessageClassificationEvidenceStrength.Weak, EmailMessageClassificationEvidenceEffect.Supports, "The DSN has no recognized recipient Action from which to determine failure or success.", "RFC 3464 section 2.3.3", "Action");
        }
    }

    EmailMessageClassificationResult CreateResult(EmailMessageClassificationKind kind, List<EmailMessageClassificationReason> reasons)
    {
        EmailMessageClassificationEvidenceStrength strongest = EmailMessageClassificationEvidenceStrength.Weak;
        bool supporting = false;
        int index = 0;
        while (index < reasons.Count)
        {
            EmailMessageClassificationReason reason = reasons[index];
            if (reason.IsSupporting())
            {
                if (!supporting || reason.GetStrength() > strongest) strongest = reason.GetStrength();
                supporting = true;
            }

            index++;
        }

        EmailMessageClassificationConfidence confidence = EmailMessageClassificationConfidence.None;
        if (supporting && strongest == EmailMessageClassificationEvidenceStrength.Weak) confidence = EmailMessageClassificationConfidence.Low;
        else if (supporting && strongest == EmailMessageClassificationEvidenceStrength.Moderate) confidence = EmailMessageClassificationConfidence.Medium;
        else if (supporting) confidence = EmailMessageClassificationConfidence.High;
        return new EmailMessageClassificationResult(kind, confidence, reasons);
    }

    void Add(EmailMessageClassificationKind kind, EmailMessageClassificationReasonCode code, EmailMessageClassificationEvidenceStrength strength, EmailMessageClassificationEvidenceEffect effect, string description, string standard, string fieldName)
    {
        EmailMessageClassificationReason reason = new EmailMessageClassificationReason(kind, code, strength, effect, description, standard, fieldName);
        if (kind == EmailMessageClassificationKind.Automated) automated.Add(reason);
        else if (kind == EmailMessageClassificationKind.MailingList) mailingList.Add(reason);
        else if (kind == EmailMessageClassificationKind.Bounce) bounce.Add(reason);
        else receipt.Add(reason);
    }

    byte[] GetBoundedValue(EmailHeader field)
    {
        byte[] value = field.GetUnfoldedValue();
        if (value.Length > options.GetMaximumHeaderValueBytes()) throw new EmailLimitException("MaxClassificationHeaderValueBytes", options.GetMaximumHeaderValueBytes(), value.Length);
        return value;
    }

    string? GetBoundedText(EmailHeader field)
    {
        GetBoundedValue(field);
        return field.GetDecodedValue();
    }

    static EmailListManagementKind GetListKind(string name)
    {
        if (string.Equals(name, "List-Unsubscribe", StringComparison.OrdinalIgnoreCase)) return EmailListManagementKind.Unsubscribe;
        if (string.Equals(name, "List-Subscribe", StringComparison.OrdinalIgnoreCase)) return EmailListManagementKind.Subscribe;
        if (string.Equals(name, "List-Post", StringComparison.OrdinalIgnoreCase)) return EmailListManagementKind.Post;
        if (string.Equals(name, "List-Owner", StringComparison.OrdinalIgnoreCase)) return EmailListManagementKind.Owner;
        if (string.Equals(name, "List-Archive", StringComparison.OrdinalIgnoreCase)) return EmailListManagementKind.Archive;
        return EmailListManagementKind.Help;
    }

    static bool IsValidListIdentifier(byte[] bytes)
    {
        string value = System.Text.Encoding.ASCII.GetString(bytes).Trim();
        int open = value.LastIndexOf('<');
        int close = value.LastIndexOf('>');
        if (open < 0 || close != value.Length - 1 || close <= open + 1) return false;
        string identifier = value.Substring(open + 1, close - open - 1);
        if (identifier.Length > 255 || identifier[0] == '.' || identifier[identifier.Length - 1] == '.' || identifier.IndexOf('.') < 1) return false;
        int rawOpen = bytes.Length - 1;
        while (rawOpen >= 0 && bytes[rawOpen] != 60) rawOpen--;
        if (rawOpen < 0) return false;
        bool previousDot = false;
        int index = 0;
        while (index < identifier.Length)
        {
            if (bytes[rawOpen + 1 + index] > 127) return false;
            char current = identifier[index];
            if (current == '.')
            {
                if (previousDot) return false;
                previousDot = true;
            }
            else
            {
                if (!IsDotAtomCharacter(current)) return false;
                previousDot = false;
            }

            index++;
        }

        return true;
    }

    static bool IsDotAtomCharacter(char value)
    {
        if (value >= 'a' && value <= 'z' || value >= 'A' && value <= 'Z' || value >= '0' && value <= '9') return true;
        return value == '!' || value == '#' || value == '$' || value == '%' || value == '&' || value == '\'' || value == '*' || value == '+' || value == '-' || value == '/' || value == '=' || value == '?' || value == '^' || value == '_' || value == '`' || value == '{' || value == '|' || value == '}' || value == '~';
    }

    static bool ContainsAny(string value, string[] candidates)
    {
        int index = 0;
        while (index < candidates.Length)
        {
            if (value.IndexOf(candidates[index], StringComparison.Ordinal) >= 0) return true;
            index++;
        }

        return false;
    }
}
