namespace jmap;

/// <summary>
/// Defines data-type names registered by JMAP Core and JMAP Mail.
/// </summary>
public static class JmapDataTypes
{
    /// <summary>The Core data type.</summary>
    public const string Core = "Core";

    /// <summary>The PushSubscription data type.</summary>
    public const string PushSubscription = "PushSubscription";

    /// <summary>The Mailbox data type.</summary>
    public const string Mailbox = "Mailbox";

    /// <summary>The Thread data type.</summary>
    public const string Thread = "Thread";

    /// <summary>The Email data type.</summary>
    public const string Email = "Email";

    /// <summary>The EmailDelivery data type used for newly delivered email.</summary>
    public const string EmailDelivery = "EmailDelivery";

    /// <summary>The SearchSnippet data type.</summary>
    public const string SearchSnippet = "SearchSnippet";

    /// <summary>The Identity data type.</summary>
    public const string Identity = "Identity";

    /// <summary>The EmailSubmission data type.</summary>
    public const string EmailSubmission = "EmailSubmission";

    /// <summary>The VacationResponse data type.</summary>
    public const string VacationResponse = "VacationResponse";
}
