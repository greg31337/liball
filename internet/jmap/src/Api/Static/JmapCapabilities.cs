namespace jmap;

/// <summary>
/// Defines capability URIs registered by JMAP Core and JMAP Mail.
/// </summary>
public static class JmapCapabilities
{
    /// <summary>The JMAP Core capability URI.</summary>
    public const string Core = "urn:ietf:params:jmap:core";

    /// <summary>The JMAP Mail capability URI.</summary>
    public const string Mail = "urn:ietf:params:jmap:mail";

    /// <summary>The JMAP Submission capability URI.</summary>
    public const string Submission = "urn:ietf:params:jmap:submission";

    /// <summary>The JMAP Vacation Response capability URI.</summary>
    public const string VacationResponse = "urn:ietf:params:jmap:vacationresponse";
}
