namespace jmap;

/// <summary>
/// Defines standard lowercase JMAP mailbox roles.
/// </summary>
public static class JmapMailboxRoles
{
    /// <summary>The all-mail mailbox role.</summary>
    public const string All = "all";

    /// <summary>The archive mailbox role.</summary>
    public const string Archive = "archive";

    /// <summary>The drafts mailbox role.</summary>
    public const string Drafts = "drafts";

    /// <summary>The flagged mailbox role.</summary>
    public const string Flagged = "flagged";

    /// <summary>The important mailbox role.</summary>
    public const string Important = "important";

    /// <summary>The inbox mailbox role.</summary>
    public const string Inbox = "inbox";

    /// <summary>The junk mailbox role.</summary>
    public const string Junk = "junk";

    /// <summary>The sent mailbox role.</summary>
    public const string Sent = "sent";

    /// <summary>The trash mailbox role.</summary>
    public const string Trash = "trash";
}
