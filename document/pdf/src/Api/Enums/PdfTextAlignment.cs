namespace pdf;

/// <summary>
/// Specifies text alignment values used by the PDF API.
/// </summary>
public enum PdfTextAlignment
{
    /// <summary>
    /// Uses the left option for text alignment.
    /// </summary>
    Left = 0,
    /// <summary>
    /// Uses the center option for text alignment.
    /// </summary>
    Center = 1,
    /// <summary>
    /// Uses the right option for text alignment.
    /// </summary>
    Right = 2,
    /// <summary>
    /// Uses the justify option for text alignment.
    /// </summary>
    Justify = 3
}
