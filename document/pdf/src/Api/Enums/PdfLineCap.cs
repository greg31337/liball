namespace pdf;

/// <summary>
/// Specifies line cap values used by the PDF API.
/// </summary>
public enum PdfLineCap
{
    /// <summary>
    /// Uses the butt option for line cap.
    /// </summary>
    Butt = 0,
    /// <summary>
    /// Uses the round option for line cap.
    /// </summary>
    Round = 1,
    /// <summary>
    /// Uses the square option for line cap.
    /// </summary>
    Square = 2
}
