namespace pdf;

/// <summary>
/// Specifies the predominant reading order used when pages are arranged side by side.
/// </summary>
public enum PdfReadingDirection
{
    /// <summary>
    /// Arranges content from left to right.
    /// </summary>
    LeftToRight = 0,
    /// <summary>
    /// Arranges content from right to left.
    /// </summary>
    RightToLeft = 1
}
