namespace pdf;

/// <summary>
/// Specifies list marker style values used by the PDF API.
/// </summary>
public enum PdfListMarkerStyle
{
    /// <summary>
    /// Uses the bullet option for list marker style.
    /// </summary>
    Bullet = 0,
    /// <summary>
    /// Uses the numbered option for list marker style.
    /// </summary>
    Numbered = 1
}
