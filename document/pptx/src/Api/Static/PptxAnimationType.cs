namespace pptx;

/// <summary>
/// Defines supported animation effect categories.
/// </summary>
public static class PptxAnimationType
{
    /// <summary>Identifies an entrance effect.</summary>
    public const string Entrance = "entrance";
    /// <summary>Identifies an emphasis effect.</summary>
    public const string Emphasis = "emphasis";
    /// <summary>Identifies an exit effect.</summary>
    public const string Exit = "exit";
    /// <summary>Identifies a motion-path effect.</summary>
    public const string MotionPath = "motion";
    /// <summary>Identifies a media command effect.</summary>
    public const string Media = "media";
}
