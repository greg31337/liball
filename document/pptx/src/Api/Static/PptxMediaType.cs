namespace pptx;

/// <summary>
/// Provides identifiers used to distinguish audio, video, and unknown media.
/// </summary>
public static class PptxMediaType
{
    /// <summary>
    /// Identifies the audio value accepted by the API.
    /// </summary>
    public const string Audio = "audio";
    /// <summary>
    /// Identifies the video value accepted by the API.
    /// </summary>
    public const string Video = "video";
    /// <summary>
    /// Identifies the unknown value accepted by the API.
    /// </summary>
    public const string Unknown = "unknown";
}

