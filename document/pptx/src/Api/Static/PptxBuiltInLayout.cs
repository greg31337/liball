namespace pptx;

/// <summary>
/// Provides stable names for the common layouts created by <see cref="PptxDeckGenerator"/>.
/// </summary>
public static class PptxBuiltInLayout
{
    /// <summary>Identifies the blank layout.</summary>
    public const string Blank = "Blank";
    /// <summary>Identifies the centered title and subtitle layout.</summary>
    public const string TitleSlide = "Title Slide";
    /// <summary>Identifies the title and single-content layout.</summary>
    public const string TitleAndContent = "Title and Content";
    /// <summary>Identifies the section-heading layout.</summary>
    public const string SectionHeader = "Section Header";
    /// <summary>Identifies the title and two-content layout.</summary>
    public const string TwoContent = "Two Content";
    /// <summary>Identifies the title-only layout.</summary>
    public const string TitleOnly = "Title Only";
}
