namespace pptx;

/// <summary>
/// Provides the bullet type identifiers used by paragraph formatting.
/// </summary>
public static class PptxBullet
{
    /// <summary>
    /// Identifies the none value accepted by the API.
    /// </summary>
    public const string None = "none";
    /// <summary>
    /// Identifies the character value accepted by the API.
    /// </summary>
    public const string Character = "character";
    /// <summary>
    /// Identifies the number value accepted by the API.
    /// </summary>
    public const string Number = "number";
    /// <summary>
    /// Identifies the picture value accepted by the API.
    /// </summary>
    public const string Picture = "picture";
}

