namespace odf;

/// <summary>
/// Identifies a three-dimensional scene projection mode.
/// </summary>
public enum OdfThreeDimensionalProjection
{
    /// <summary>The projection value is absent or unrecognized.</summary>
    Unknown = 0,
    /// <summary>Parallel projection.</summary>
    Parallel = 1,
    /// <summary>Perspective projection.</summary>
    Perspective = 2
}
