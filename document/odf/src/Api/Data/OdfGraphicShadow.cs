namespace odf;

/// <summary>
/// Describes graphic shadow visibility, placement, color, and opacity.
/// </summary>
public class OdfGraphicShadow
{
    /// <summary>The shadow visibility value.</summary>
    public string Visibility = "";
    /// <summary>The horizontal shadow offset.</summary>
    public string OffsetX = "";
    /// <summary>The vertical shadow offset.</summary>
    public string OffsetY = "";
    /// <summary>The shadow color.</summary>
    public string Color = "";
    /// <summary>The shadow opacity.</summary>
    public string Opacity = "";
}
