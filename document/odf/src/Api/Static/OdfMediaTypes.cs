namespace odf;

/// <summary>
/// Provides standard OpenDocument and common part media types.
/// </summary>
public static class OdfMediaTypes
{
    /// <summary>
    /// The database front-end document media type.
    /// </summary>
    public const string Base = "application/vnd.oasis.opendocument.base";
    /// <summary>
    /// The text document media type.
    /// </summary>
    public const string Text = "application/vnd.oasis.opendocument.text";
    /// <summary>
    /// The text template media type.
    /// </summary>
    public const string TextTemplate = "application/vnd.oasis.opendocument.text-template";
    /// <summary>
    /// The master text document media type.
    /// </summary>
    public const string TextMaster = "application/vnd.oasis.opendocument.text-master";
    /// <summary>
    /// The master text template media type.
    /// </summary>
    public const string TextMasterTemplate = "application/vnd.oasis.opendocument.text-master-template";
    /// <summary>
    /// The spreadsheet document media type.
    /// </summary>
    public const string Spreadsheet = "application/vnd.oasis.opendocument.spreadsheet";
    /// <summary>
    /// The spreadsheet template media type.
    /// </summary>
    public const string SpreadsheetTemplate = "application/vnd.oasis.opendocument.spreadsheet-template";
    /// <summary>
    /// The presentation document media type.
    /// </summary>
    public const string Presentation = "application/vnd.oasis.opendocument.presentation";
    /// <summary>
    /// The presentation template media type.
    /// </summary>
    public const string PresentationTemplate = "application/vnd.oasis.opendocument.presentation-template";
    /// <summary>
    /// The drawing document media type.
    /// </summary>
    public const string Graphics = "application/vnd.oasis.opendocument.graphics";
    /// <summary>
    /// The drawing template media type.
    /// </summary>
    public const string GraphicsTemplate = "application/vnd.oasis.opendocument.graphics-template";
    /// <summary>
    /// The chart document media type.
    /// </summary>
    public const string Chart = "application/vnd.oasis.opendocument.chart";
    /// <summary>
    /// The chart template media type.
    /// </summary>
    public const string ChartTemplate = "application/vnd.oasis.opendocument.chart-template";
    /// <summary>
    /// The formula document media type.
    /// </summary>
    public const string Formula = "application/vnd.oasis.opendocument.formula";
    /// <summary>
    /// The formula template media type.
    /// </summary>
    public const string FormulaTemplate = "application/vnd.oasis.opendocument.formula-template";
    /// <summary>
    /// The image document media type.
    /// </summary>
    public const string Image = "application/vnd.oasis.opendocument.image";
    /// <summary>
    /// The image template media type.
    /// </summary>
    public const string ImageTemplate = "application/vnd.oasis.opendocument.image-template";
    /// <summary>
    /// The media type used for standard ODF XML parts.
    /// </summary>
    public const string Xml = "text/xml";
    /// <summary>
    /// The RDF/XML media type.
    /// </summary>
    public const string RdfXml = "application/rdf+xml";
    /// <summary>
    /// The MathML media type.
    /// </summary>
    public const string MathMl = "application/mathml+xml";
    /// <summary>
    /// The SVG image media type.
    /// </summary>
    public const string Svg = "image/svg+xml";
    /// <summary>
    /// The PNG image media type.
    /// </summary>
    public const string Png = "image/png";
    /// <summary>
    /// The JPEG image media type.
    /// </summary>
    public const string Jpeg = "image/jpeg";
    /// <summary>
    /// The GIF image media type.
    /// </summary>
    public const string Gif = "image/gif";
    /// <summary>
    /// The bitmap image media type.
    /// </summary>
    public const string Bmp = "image/bmp";
    /// <summary>
    /// The TIFF image media type.
    /// </summary>
    public const string Tiff = "image/tiff";
    /// <summary>
    /// The WebP image media type.
    /// </summary>
    public const string WebP = "image/webp";
    /// <summary>
    /// The ZIP archive media type.
    /// </summary>
    public const string Zip = "application/zip";
    /// <summary>
    /// The generic binary media type.
    /// </summary>
    public const string OctetStream = "application/octet-stream";
}
