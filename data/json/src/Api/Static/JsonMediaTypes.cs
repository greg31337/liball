namespace json;

/// <summary>Provides registered media types for JSON and JSON text sequences.</summary>
public static class JsonMediaTypes
{
    /// <summary>The media type for a JSON value.</summary>
    public const string ApplicationJson = "application/json";

    /// <summary>The media type for an RFC 7464 JSON text sequence.</summary>
    public const string ApplicationJsonSequence = "application/json-seq";
}
