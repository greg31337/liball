#!/usr/bin/env python3
"""Generate the checked-in Shift JIS and GB2312 lookup tables."""

from __future__ import annotations

import hashlib
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
UNICODE_DIRECTORY = ROOT / "specs" / "unicode"
TABLE_DIRECTORY = ROOT / "src" / "Internal" / "Tables"

SOURCES = {
    "SHIFTJIS.TXT": "52d6467329db0753c4a658591a3b2b2efdf9bef39ea11d6d1c0c4187917a2368",
    "CP932.TXT": "c9bc0b0cd42e0fbcb82a09635bb5abed86afbdd4abc9e76fa5716638217cb59f",
    "GB2312.TXT": "52335c54396c41d3e04856cb6018bd600469f210556233aa9895b1f396b257ed",
    "CP936.TXT": "b86f601c575e9ab457380b6f7abef03c75499cc6075bdc8b4b27f3f2de74bf6a",
}

MAPPING_LINE = re.compile(r"^0x([0-9A-Fa-f]+)\s+0x([0-9A-Fa-f]+)(?:\s|$)")


def read_mapping(name: str) -> dict[int, int]:
    path = UNICODE_DIRECTORY / name
    actual_hash = hashlib.sha256(path.read_bytes()).hexdigest()
    expected_hash = SOURCES[name]
    if actual_hash != expected_hash:
        raise ValueError(f"{name} has SHA-256 {actual_hash}; expected {expected_hash}")

    mappings: dict[int, int] = {}
    for line_number, line in enumerate(path.read_text(encoding="utf-8-sig").splitlines(), 1):
        match = MAPPING_LINE.match(line)
        if match is None:
            continue
        encoded_value = int(match.group(1), 16)
        unicode_value = int(match.group(2), 16)
        if encoded_value in mappings:
            raise ValueError(f"duplicate encoded value in {name}:{line_number}")
        mappings[encoded_value] = unicode_value
    return mappings


def create_reverse(mapping: dict[int, int]) -> dict[int, int]:
    reverse: dict[int, int] = {}
    for encoded_value, unicode_value in sorted(mapping.items()):
        if unicode_value not in reverse:
            reverse[unicode_value] = encoded_value
    return reverse


def format_pairs(mapping: dict[int, int]) -> str:
    values = [f"0x{key:04X}, 0x{value:04X}" for key, value in sorted(mapping.items())]
    lines = []
    for index in range(0, len(values), 4):
        lines.append("        " + ", ".join(values[index:index + 4]) + ",")
    return "\n".join(lines)


def render_class(
    class_name: str,
    standard: dict[int, int],
    vendor: dict[int, int],
    standard_name: str,
    vendor_name: str,
) -> str:
    standard_reverse = create_reverse(standard)
    vendor_reverse = create_reverse(vendor)
    standard_hash = SOURCES[standard_name]
    vendor_hash = SOURCES[vendor_name]
    return f"""// Generated by specs/tools/generate_character_tables.py. Do not edit by hand.
namespace qrcode;

internal class {class_name}
{{
    internal const int NotMapped = -1;
    internal const int StandardMappingCount = {len(standard)};
    internal const int VendorMappingCount = {len(vendor)};
    internal const string StandardSource = "{standard_name}";
    internal const string StandardSourceSha256 = "{standard_hash}";
    internal const string VendorSource = "{vendor_name}";
    internal const string VendorSourceSha256 = "{vendor_hash}";

    static readonly int[] StandardByCode = new int[]
    {{
{format_pairs(standard)}
    }};

    static readonly int[] VendorByCode = new int[]
    {{
{format_pairs(vendor)}
    }};

    static readonly int[] StandardByUnicode = new int[]
    {{
{format_pairs(standard_reverse)}
    }};

    static readonly int[] VendorByUnicode = new int[]
    {{
{format_pairs(vendor_reverse)}
    }};

    internal static int GetStandardUnicode(int encodedValue)
    {{
        return FindMapping(StandardByCode, encodedValue);
    }}

    internal static int GetVendorUnicode(int encodedValue)
    {{
        return FindMapping(VendorByCode, encodedValue);
    }}

    internal static int GetUnicode(int encodedValue, bool includeVendorMappings)
    {{
        if (includeVendorMappings)
        {{
            int vendorValue = FindMapping(VendorByCode, encodedValue);
            if (vendorValue != NotMapped)
            {{
                return vendorValue;
            }}
        }}

        return FindMapping(StandardByCode, encodedValue);
    }}

    internal static int GetStandardEncodedValue(int unicodeValue)
    {{
        return FindMapping(StandardByUnicode, unicodeValue);
    }}

    internal static int GetVendorEncodedValue(int unicodeValue)
    {{
        return FindMapping(VendorByUnicode, unicodeValue);
    }}

    internal static int GetEncodedValue(int unicodeValue, bool includeVendorMappings)
    {{
        int encodedValue = FindMapping(StandardByUnicode, unicodeValue);
        if (encodedValue != NotMapped || !includeVendorMappings)
        {{
            return encodedValue;
        }}

        return FindMapping(VendorByUnicode, unicodeValue);
    }}

    internal static bool IsVendorOverride(int encodedValue)
    {{
        return FindMapping(StandardByCode, encodedValue) != NotMapped
            && FindMapping(VendorByCode, encodedValue) != NotMapped;
    }}

    internal static int GetStandardEncodedValueAt(int index)
    {{
        ValidateIndex(index, StandardMappingCount);
        return StandardByCode[index * 2];
    }}

    internal static int GetStandardUnicodeAt(int index)
    {{
        ValidateIndex(index, StandardMappingCount);
        return StandardByCode[index * 2 + 1];
    }}

    internal static int GetVendorEncodedValueAt(int index)
    {{
        ValidateIndex(index, VendorMappingCount);
        return VendorByCode[index * 2];
    }}

    internal static int GetVendorUnicodeAt(int index)
    {{
        ValidateIndex(index, VendorMappingCount);
        return VendorByCode[index * 2 + 1];
    }}

    static int FindMapping(int[] mappings, int key)
    {{
        int low = 0;
        int high = mappings.Length / 2 - 1;
        while (low <= high)
        {{
            int middle = low + (high - low) / 2;
            int candidate = mappings[middle * 2];
            if (candidate < key)
            {{
                low = middle + 1;
            }}
            else if (candidate > key)
            {{
                high = middle - 1;
            }}
            else
            {{
                return mappings[middle * 2 + 1];
            }}
        }}

        return NotMapped;
    }}

    static void ValidateIndex(int index, int count)
    {{
        if (index < 0 || index >= count)
        {{
            throw new global::System.ArgumentOutOfRangeException("index");
        }}
    }}
}}
"""


def main() -> None:
    shift_jis = read_mapping("SHIFTJIS.TXT")
    cp932 = read_mapping("CP932.TXT")
    shift_jis_vendor = {
        code: unicode_value
        for code, unicode_value in cp932.items()
        if (code > 0xFF or code in shift_jis) and shift_jis.get(code) != unicode_value
    }

    gb2312_row_cell = read_mapping("GB2312.TXT")
    gb2312 = {code + 0x8080: unicode_value for code, unicode_value in gb2312_row_cell.items()}
    cp936 = read_mapping("CP936.TXT")
    gb2312_vendor = {
        code: unicode_value
        for code, unicode_value in cp936.items()
        if code > 0xFF and gb2312.get(code) != unicode_value
    }

    TABLE_DIRECTORY.mkdir(parents=True, exist_ok=True)
    (TABLE_DIRECTORY / "ShiftJisTable.cs").write_text(
        render_class("ShiftJisTable", shift_jis, shift_jis_vendor, "SHIFTJIS.TXT", "CP932.TXT"),
        encoding="utf-8",
    )
    (TABLE_DIRECTORY / "Gb2312Table.cs").write_text(
        render_class("Gb2312Table", gb2312, gb2312_vendor, "GB2312.TXT", "CP936.TXT"),
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
