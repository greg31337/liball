namespace qrcode;

/// <summary>Identifies an automatic or explicitly selected QR mask pattern.</summary>
public enum QrMaskPattern
{
    /// <summary>Selects the best permitted mask automatically.</summary>
    Automatic = -1,

    /// <summary>Selects mask pattern zero.</summary>
    Zero = 0,

    /// <summary>Selects mask pattern one.</summary>
    One = 1,

    /// <summary>Selects mask pattern two.</summary>
    Two = 2,

    /// <summary>Selects mask pattern three.</summary>
    Three = 3,

    /// <summary>Selects mask pattern four.</summary>
    Four = 4,

    /// <summary>Selects mask pattern five.</summary>
    Five = 5,

    /// <summary>Selects mask pattern six.</summary>
    Six = 6,

    /// <summary>Selects mask pattern seven.</summary>
    Seven = 7
}
