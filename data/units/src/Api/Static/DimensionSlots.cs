namespace units;

/// <summary>
/// Defines the stable slot indexes used by dimension vectors.
/// </summary>
public static class DimensionSlots
{
    /// <summary>
    /// Identifies the length exponent slot.
    /// </summary>
    public const int Length = 0;
    /// <summary>
    /// Identifies the mass exponent slot.
    /// </summary>
    public const int Mass = 1;
    /// <summary>
    /// Identifies the time exponent slot.
    /// </summary>
    public const int Time = 2;
    /// <summary>
    /// Identifies the electric-current exponent slot.
    /// </summary>
    public const int ElectricCurrent = 3;
    /// <summary>
    /// Identifies the thermodynamic-temperature exponent slot.
    /// </summary>
    public const int ThermodynamicTemperature = 4;
    /// <summary>
    /// Identifies the amount-of-substance exponent slot.
    /// </summary>
    public const int AmountOfSubstance = 5;
    /// <summary>
    /// Identifies the luminous-intensity exponent slot.
    /// </summary>
    public const int LuminousIntensity = 6;
    /// <summary>
    /// Identifies the plane-angle exponent slot.
    /// </summary>
    public const int PlaneAngle = 7;
    /// <summary>
    /// Identifies the solid-angle exponent slot.
    /// </summary>
    public const int SolidAngle = 8;
    /// <summary>
    /// Identifies the information exponent slot.
    /// </summary>
    public const int Information = 9;
    /// <summary>
    /// Identifies the currency exponent slot.
    /// </summary>
    public const int Currency = 10;
    /// <summary>
    /// Identifies the count exponent slot.
    /// </summary>
    public const int Count = 11;
}
