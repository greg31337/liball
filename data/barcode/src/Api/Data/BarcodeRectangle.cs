namespace barcode;

/// <summary>
/// Holds an axis-aligned image region or bounding rectangle.
/// </summary>
public class BarcodeRectangle
{
    /// <summary>
    /// The horizontal coordinate of the left edge.
    /// </summary>
    public double X;

    /// <summary>
    /// The vertical coordinate of the top edge.
    /// </summary>
    public double Y;

    /// <summary>
    /// The rectangle width.
    /// </summary>
    public double Width;

    /// <summary>
    /// The rectangle height.
    /// </summary>
    public double Height;
}
