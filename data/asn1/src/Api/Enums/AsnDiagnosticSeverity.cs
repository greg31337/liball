namespace asn1;

/// <summary>
/// Identifies the severity of a diagnostic.
/// </summary>
public enum AsnDiagnosticSeverity
{
    /// <summary>
    /// Represents information.
    /// </summary>
    Information = 0,

    /// <summary>
    /// Represents warning.
    /// </summary>
    Warning = 1,

    /// <summary>
    /// Represents error.
    /// </summary>
    Error = 2
}
