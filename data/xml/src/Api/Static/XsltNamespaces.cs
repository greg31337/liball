namespace xml;

/// <summary>
/// Provides standard XSLT namespace URIs.
/// </summary>
public static class XsltNamespaces
{
    /// <summary>
    /// The XSLT namespace URI.
    /// </summary>
    public const string Xslt = "http://www.w3.org/1999/XSL/Transform";
    /// <summary>
    /// The XSLT error namespace URI.
    /// </summary>
    public const string Errors = "http://www.w3.org/2005/xqt-errors";
    /// <summary>
    /// The Serialization 3.1 parameter namespace URI.
    /// </summary>
    public const string Serialization = "http://www.w3.org/2010/xslt-xquery-serialization";
}

