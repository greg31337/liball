namespace xml;

/// <summary>
/// Provides standard XML namespace URIs.
/// </summary>
public static class XmlNamespaces
{
    /// <summary>
    /// The reserved XML namespace URI.
    /// </summary>
    public const string Xml = "http://www.w3.org/XML/1998/namespace";
    /// <summary>
    /// The reserved XML namespace declaration URI.
    /// </summary>
    public const string Xmlns = "http://www.w3.org/2000/xmlns/";
    /// <summary>
    /// The XInclude namespace URI.
    /// </summary>
    public const string XInclude = "http://www.w3.org/2001/XInclude";
    /// <summary>
    /// The XPointer namespace URI.
    /// </summary>
    public const string XPointer = "http://www.w3.org/2001/XPointer";
    /// <summary>
    /// The OASIS XML Catalog namespace URI.
    /// </summary>
    public const string Catalog = "urn:oasis:names:tc:entity:xmlns:xml:catalog";
    /// <summary>
    /// The XML Schema namespace URI.
    /// </summary>
    public const string XmlSchema = "http://www.w3.org/2001/XMLSchema";
    /// <summary>
    /// The XML Schema instance namespace URI.
    /// </summary>
    public const string XmlSchemaInstance = "http://www.w3.org/2001/XMLSchema-instance";
}

