namespace xml;

/// <summary>
/// Provides standard XPath namespace and collation URIs.
/// </summary>
public static class XPathNamespaces
{
    /// <summary>
    /// The XPath functions namespace URI.
    /// </summary>
    public const string Functions = "http://www.w3.org/2005/xpath-functions";
    /// <summary>
    /// The XPath math functions namespace URI.
    /// </summary>
    public const string Math = "http://www.w3.org/2005/xpath-functions/math";
    /// <summary>
    /// The XPath map functions namespace URI.
    /// </summary>
    public const string Map = "http://www.w3.org/2005/xpath-functions/map";
    /// <summary>
    /// The XPath array functions namespace URI.
    /// </summary>
    public const string Array = "http://www.w3.org/2005/xpath-functions/array";
    /// <summary>
    /// The XML Schema datatype namespace URI.
    /// </summary>
    public const string XmlSchema = "http://www.w3.org/2001/XMLSchema";
    /// <summary>
    /// The XPath and XQuery error namespace URI.
    /// </summary>
    public const string Errors = "http://www.w3.org/2005/xqt-errors";
    /// <summary>
    /// The Unicode codepoint collation URI.
    /// </summary>
    public const string CodepointCollation = "http://www.w3.org/2005/xpath-functions/collation/codepoint";
}
