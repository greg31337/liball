namespace xml;

/// <summary>
/// Provides XML media types and encoding names.
/// </summary>
public static class XmlMediaTypes
{
    /// <summary>
    /// The application XML media type.
    /// </summary>
    public const string ApplicationXml = "application/xml";
    /// <summary>
    /// The text XML media type.
    /// </summary>
    public const string TextXml = "text/xml";
    /// <summary>
    /// The application external parsed entity media type.
    /// </summary>
    public const string ApplicationXmlExternalParsedEntity = "application/xml-external-parsed-entity";
    /// <summary>
    /// The text external parsed entity media type.
    /// </summary>
    public const string TextXmlExternalParsedEntity = "text/xml-external-parsed-entity";
    /// <summary>
    /// The XML DTD media type.
    /// </summary>
    public const string ApplicationXmlDtd = "application/xml-dtd";
    /// <summary>
    /// The UTF-8 encoding name.
    /// </summary>
    public const string Utf8 = "UTF-8";
    /// <summary>
    /// The UTF-16 encoding name.
    /// </summary>
    public const string Utf16 = "UTF-16";
    /// <summary>
    /// The big-endian UTF-16 encoding name.
    /// </summary>
    public const string Utf16BigEndian = "UTF-16BE";
    /// <summary>
    /// The little-endian UTF-16 encoding name.
    /// </summary>
    public const string Utf16LittleEndian = "UTF-16LE";
    /// <summary>
    /// The US-ASCII encoding name.
    /// </summary>
    public const string UsAscii = "US-ASCII";
}

