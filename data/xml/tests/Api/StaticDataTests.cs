    private static void AssertFields(Type type, Dictionary<string, string> expected)
    {
        FieldInfo[] fields = type.GetFields(BindingFlags.Public | BindingFlags.Static);
        Assert.That(fields.Length, Is.EqualTo(expected.Count), type.Name);
        foreach (FieldInfo field in fields)
        {
            Assert.That(expected.ContainsKey(field.Name), Is.True, type.Name + "." + field.Name);
            Assert.That(field.GetValue(null), Is.EqualTo(expected[field.Name]), type.Name + "." + field.Name);
        }
    }
