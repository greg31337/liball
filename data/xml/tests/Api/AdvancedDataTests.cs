    [Test]
    public void XdmDataPreservesHeterogeneousOrderAndContainerMetadata()
    {
        XmlName atomicName = new XmlName();
        atomicName.LocalName = "name";
        XmlSchemaTypeInfo typeInfo = new XmlSchemaTypeInfo();
        XdmAtomicValue atomic = new XdmAtomicValue();
        atomic.Type = XdmAtomicType.QName;
        atomic.LexicalValue = "p:name";
        atomic.CanonicalValue = "p:name";
        atomic.StringValue = "p:name";
        atomic.BooleanValue = true;
        atomic.DecimalValue = 12.5m;
        atomic.IntegerValue = 12;
        atomic.FloatingValue = 12.5;
        atomic.BinaryValue = [1, 2];
        atomic.NameValue = atomicName;
        atomic.ExtendedValue = DateTimeOffset.UnixEpoch;
        atomic.TypeInfo = typeInfo;
        XdmSequence atomicSequence = new XdmSequence();
        atomicSequence.ItemKinds = [XdmItemKind.Atomic];
        atomicSequence.ItemIndexes = [0];
        atomicSequence.AtomicValues = [atomic];
        atomicSequence.Count = 1;
        atomicSequence.IsImmutable = true;
        XdmMapEntry entry = new XdmMapEntry();
        entry.Key = atomic;
        entry.Value = atomicSequence;
        XdmMapValue map = new XdmMapValue();
        map.Entries = [entry];
        map.Count = 1;
        map.IsImmutable = true;
        XdmArrayValue array = new XdmArrayValue();
        array.Members = [atomicSequence];
        array.Count = 1;
        array.IsImmutable = true;
        XdmFunctionItem function = new XdmFunctionItem();
        function.Name = atomicName;
        function.Arity = 1;
        function.ParameterTypes = [XdmAtomicType.String];
        function.ParameterOccurrences = [XdmOccurrence.ExactlyOne];
        function.ResultType = XdmAtomicType.Boolean;
        function.ResultOccurrence = XdmOccurrence.ZeroOrOne;
        function.BindingKey = "function-key";
        function.IsMap = false;
        function.IsArray = false;
        XmlNode node = new XmlNode();
        node.Kind = XmlNodeKind.Element;
        XdmSequence mixed = new XdmSequence();
        mixed.ItemKinds = [XdmItemKind.Node, XdmItemKind.Atomic, XdmItemKind.Map, XdmItemKind.Array, XdmItemKind.Function];
        mixed.ItemIndexes = [0, 0, 0, 0, 0];
        mixed.Nodes = [node];
        mixed.AtomicValues = [atomic];
        mixed.Maps = [map];
        mixed.Arrays = [array];
        mixed.Functions = [function];
        mixed.Count = 5;
        mixed.IsImmutable = true;

        Assert.That(atomic.Type, Is.EqualTo(XdmAtomicType.QName));
        Assert.That(atomic.LexicalValue, Is.EqualTo("p:name"));
        Assert.That(atomic.CanonicalValue, Is.EqualTo("p:name"));
        Assert.That(atomic.StringValue, Is.EqualTo("p:name"));
        Assert.That(atomic.BooleanValue, Is.True);
        Assert.That(atomic.DecimalValue, Is.EqualTo(12.5m));
        Assert.That(atomic.IntegerValue, Is.EqualTo(12));
        Assert.That(atomic.FloatingValue, Is.EqualTo(12.5));
        Assert.That(atomic.BinaryValue, Is.EqualTo(new byte[] { 1, 2 }));
        Assert.That(atomic.NameValue, Is.SameAs(atomicName));
        Assert.That(atomic.ExtendedValue, Is.EqualTo(DateTimeOffset.UnixEpoch));
        Assert.That(atomic.TypeInfo, Is.SameAs(typeInfo));
        Assert.That(entry.Key, Is.SameAs(atomic));
        Assert.That(entry.Value, Is.SameAs(atomicSequence));
        Assert.That(map.Entries, Is.EqualTo(new XdmMapEntry[] { entry }));
        Assert.That(map.Count, Is.EqualTo(1));
        Assert.That(map.IsImmutable, Is.True);
        Assert.That(array.Members, Is.EqualTo(new XdmSequence[] { atomicSequence }));
        Assert.That(array.Count, Is.EqualTo(1));
        Assert.That(array.IsImmutable, Is.True);
        Assert.That(function.Name, Is.SameAs(atomicName));
        Assert.That(function.Arity, Is.EqualTo(1));
        Assert.That(function.ParameterTypes, Is.EqualTo(new XdmAtomicType[] { XdmAtomicType.String }));
        Assert.That(function.ParameterOccurrences, Is.EqualTo(new XdmOccurrence[] { XdmOccurrence.ExactlyOne }));
        Assert.That(function.ResultType, Is.EqualTo(XdmAtomicType.Boolean));
        Assert.That(function.ResultOccurrence, Is.EqualTo(XdmOccurrence.ZeroOrOne));
        Assert.That(function.BindingKey, Is.EqualTo("function-key"));
        Assert.That(function.IsMap, Is.False);
        Assert.That(function.IsArray, Is.False);
        Assert.That(mixed.ItemKinds, Is.EqualTo(new XdmItemKind[] { XdmItemKind.Node, XdmItemKind.Atomic, XdmItemKind.Map, XdmItemKind.Array, XdmItemKind.Function }));
        Assert.That(mixed.ItemIndexes, Is.EqualTo(new int[] { 0, 0, 0, 0, 0 }));
        Assert.That(mixed.Nodes, Is.EqualTo(new XmlNode[] { node }));
        Assert.That(mixed.AtomicValues, Is.EqualTo(new XdmAtomicValue[] { atomic }));
        Assert.That(mixed.Maps, Is.EqualTo(new XdmMapValue[] { map }));
        Assert.That(mixed.Arrays, Is.EqualTo(new XdmArrayValue[] { array }));
        Assert.That(mixed.Functions, Is.EqualTo(new XdmFunctionItem[] { function }));
        Assert.That(mixed.Count, Is.EqualTo(5));
        Assert.That(mixed.IsImmutable, Is.True);
    }

    [Test]
    public void XPathDataCarriesStaticDynamicAndEvaluationSnapshots()
    {
        XmlName name = new XmlName();
        name.LocalName = "value";
        XdmSequence value = new XdmSequence();
        XPathVariableBinding variable = new XPathVariableBinding();
        variable.Name = name;
        variable.Value = value;
        variable.DeclaredType = XdmAtomicType.String;
        variable.DeclaredOccurrence = XdmOccurrence.ZeroOrMore;
        variable.IsExternal = true;
        variable.IsRequired = true;
        XPathFunctionBinding function = new XPathFunctionBinding();
        function.Name = name;
        function.Arity = 2;
        function.ParameterTypes = [XdmAtomicType.String, XdmAtomicType.Integer];
        function.ParameterOccurrences = [XdmOccurrence.ExactlyOne, XdmOccurrence.ZeroOrOne];
        function.ResultType = XdmAtomicType.Boolean;
        function.ResultOccurrence = XdmOccurrence.ExactlyOne;
        function.BindingKey = "binding";
        function.IsDeterministic = true;
        XmlSchemaSet schemas = new XmlSchemaSet();
        XmlResolverPolicy policy = new XmlResolverPolicy();
        XPathStaticContext staticContext = new XPathStaticContext();
        staticContext.LanguageVersion = XPathLanguageVersion.XPath31;
        staticContext.CompatibilityMode = XPathCompatibilityMode.BackwardsCompatible;
        staticContext.Namespaces = [new XmlNamespaceBinding()];
        staticContext.DefaultElementNamespace = "urn:elements";
        staticContext.DefaultFunctionNamespace = XPathNamespaces.Functions;
        staticContext.BaseUri = "file:///query.xq";
        staticContext.DefaultCollation = XPathNamespaces.CodepointCollation;
        staticContext.Collations = [XPathNamespaces.CodepointCollation];
        staticContext.Variables = [variable];
        staticContext.Functions = [function];
        staticContext.SchemaSet = schemas;
        staticContext.DecimalFormats = [name];
        staticContext.EnabledFeatures = ["higher-order-functions"];
        staticContext.ResolverPolicy = policy;
        staticContext.SchemaAware = true;
        staticContext.AllowHigherOrderFunctions = true;
        XmlSecurityLimits limits = new XmlSecurityLimits();
        DateTimeOffset now = new DateTimeOffset(2026, 1, 2, 3, 4, 5, TimeSpan.Zero);
        XPathDynamicContext dynamicContext = new XPathDynamicContext();
        dynamicContext.ContextItem = value;
        dynamicContext.Position = 2;
        dynamicContext.Size = 3;
        dynamicContext.Variables = [variable];
        dynamicContext.BaseUri = "file:///dynamic.xml";
        dynamicContext.DefaultCollectionUri = "urn:collection";
        dynamicContext.ImplicitTimezoneMinutes = -480;
        dynamicContext.CurrentDateTime = now;
        dynamicContext.EnvironmentNames = ["NAME"];
        dynamicContext.EnvironmentValues = ["VALUE"];
        dynamicContext.ResolverPolicy = policy;
        dynamicContext.SecurityLimits = limits;
        dynamicContext.MaximumOperations = 1000;
        SourceRange range = new SourceRange();
        object plan = new object();
        XPathCompiledExpression compiled = new XPathCompiledExpression();
        compiled.Source = "$value";
        compiled.StaticContext = staticContext;
        compiled.Plan = plan;
        compiled.Range = range;
        compiled.Diagnostics = [new XmlDiagnostic()];
        compiled.IsThreadSafe = true;
        XPathEvaluationResult result = new XPathEvaluationResult();
        result.Expression = compiled;
        result.DynamicContext = dynamicContext;
        result.Value = value;
        result.Diagnostics = [new XmlDiagnostic()];
        result.ErrorCode = XPathErrorCodes.XPDY0002;
        result.Succeeded = false;

        Assert.That(variable.Name, Is.SameAs(name));
        Assert.That(variable.Value, Is.SameAs(value));
        Assert.That(variable.DeclaredType, Is.EqualTo(XdmAtomicType.String));
        Assert.That(variable.DeclaredOccurrence, Is.EqualTo(XdmOccurrence.ZeroOrMore));
        Assert.That(variable.IsExternal, Is.True);
        Assert.That(variable.IsRequired, Is.True);
        Assert.That(function.Arity, Is.EqualTo(2));
        Assert.That(function.ParameterTypes, Is.EqualTo(new XdmAtomicType[] { XdmAtomicType.String, XdmAtomicType.Integer }));
        Assert.That(function.ParameterOccurrences, Has.Length.EqualTo(2));
        Assert.That(function.ResultType, Is.EqualTo(XdmAtomicType.Boolean));
        Assert.That(function.ResultOccurrence, Is.EqualTo(XdmOccurrence.ExactlyOne));
        Assert.That(function.BindingKey, Is.EqualTo("binding"));
        Assert.That(function.IsDeterministic, Is.True);
        Assert.That(staticContext.LanguageVersion, Is.EqualTo(XPathLanguageVersion.XPath31));
        Assert.That(staticContext.CompatibilityMode, Is.EqualTo(XPathCompatibilityMode.BackwardsCompatible));
        Assert.That(staticContext.Namespaces, Has.Length.EqualTo(1));
        Assert.That(staticContext.DefaultElementNamespace, Is.EqualTo("urn:elements"));
        Assert.That(staticContext.DefaultFunctionNamespace, Is.EqualTo(XPathNamespaces.Functions));
        Assert.That(staticContext.BaseUri, Is.EqualTo("file:///query.xq"));
        Assert.That(staticContext.DefaultCollation, Is.EqualTo(XPathNamespaces.CodepointCollation));
        Assert.That(staticContext.Collations, Is.EqualTo(new string[] { XPathNamespaces.CodepointCollation }));
        Assert.That(staticContext.Variables, Is.EqualTo(new XPathVariableBinding[] { variable }));
        Assert.That(staticContext.Functions, Is.EqualTo(new XPathFunctionBinding[] { function }));
        Assert.That(staticContext.SchemaSet, Is.SameAs(schemas));
        Assert.That(staticContext.DecimalFormats, Is.EqualTo(new XmlName[] { name }));
        Assert.That(staticContext.EnabledFeatures, Is.EqualTo(new string[] { "higher-order-functions" }));
        Assert.That(staticContext.ResolverPolicy, Is.SameAs(policy));
        Assert.That(staticContext.SchemaAware, Is.True);
        Assert.That(staticContext.AllowHigherOrderFunctions, Is.True);
        Assert.That(dynamicContext.ContextItem, Is.SameAs(value));
        Assert.That(dynamicContext.Position, Is.EqualTo(2));
        Assert.That(dynamicContext.Size, Is.EqualTo(3));
        Assert.That(dynamicContext.Variables, Is.EqualTo(new XPathVariableBinding[] { variable }));
        Assert.That(dynamicContext.BaseUri, Is.EqualTo("file:///dynamic.xml"));
        Assert.That(dynamicContext.DefaultCollectionUri, Is.EqualTo("urn:collection"));
