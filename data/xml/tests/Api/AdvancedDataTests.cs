    [Test]
    public void SchemaDataCarriesCompiledSetAnnotationsAndValidationOutcome()
    {
        XmlDocument schemaDocument = new XmlDocument();
        object compiledHandle = new object();
        XmlSchemaSet set = new XmlSchemaSet();
        set.SchemaDocuments = [schemaDocument];
        set.TargetNamespaces = ["urn:schema"];
        set.CompiledSet = compiledHandle;
        set.Diagnostics = [new XmlDiagnostic()];
        set.IsImmutable = true;
        XmlSchemaValidationOptions options = new XmlSchemaValidationOptions();
        options.ProcessContents = XmlSchemaProcessContents.Lax;
        options.FailFast = true;
        options.AnnotateTree = true;
        options.UseLocationHints = true;
        options.ApplyDefaultValues = true;
        options.ResolverPolicy = new XmlResolverPolicy();
        options.SecurityLimits = new XmlSecurityLimits();
        options.SchemaSet = set;
        XdmAtomicValue actual = new XdmAtomicValue();
        actual.StringValue = "42";
        XmlSchemaTypeInfo info = new XmlSchemaTypeInfo();
        info.TypeName = new XmlName();
        info.MemberTypeName = new XmlName();
        info.AtomicType = XdmAtomicType.Int;
        info.Validity = XmlSchemaValidity.Valid;
        info.IsNilled = true;
        info.IsId = true;
        info.IsIdReference = true;
        info.NormalizedValue = "42";
        info.ActualValue = actual;
        XmlDocument document = new XmlDocument();
        XmlSchemaValidationResult result = new XmlSchemaValidationResult();
        result.Document = document;
        result.SchemaSet = set;
        result.Options = options;
        result.Validity = XmlSchemaValidity.Invalid;
        result.TypeAnnotations = [info];
        result.Diagnostics = [new XmlDiagnostic()];
        result.Succeeded = true;

        Assert.That(set.SchemaDocuments, Is.EqualTo(new XmlDocument[] { schemaDocument }));
        Assert.That(set.TargetNamespaces, Is.EqualTo(new string[] { "urn:schema" }));
        Assert.That(set.CompiledSet, Is.SameAs(compiledHandle));
        Assert.That(set.Diagnostics, Has.Length.EqualTo(1));
        Assert.That(set.IsImmutable, Is.True);
        Assert.That(options.ProcessContents, Is.EqualTo(XmlSchemaProcessContents.Lax));
        Assert.That(options.FailFast, Is.True);
        Assert.That(options.AnnotateTree, Is.True);
        Assert.That(options.UseLocationHints, Is.True);
        Assert.That(options.ApplyDefaultValues, Is.True);
        Assert.That(options.ResolverPolicy, Is.Not.Null);
        Assert.That(options.SecurityLimits, Is.Not.Null);
        Assert.That(options.SchemaSet, Is.SameAs(set));
        Assert.That(info.TypeName, Is.Not.Null);
        Assert.That(info.MemberTypeName, Is.Not.Null);
        Assert.That(info.AtomicType, Is.EqualTo(XdmAtomicType.Int));
        Assert.That(info.Validity, Is.EqualTo(XmlSchemaValidity.Valid));
        Assert.That(info.IsNilled, Is.True);
        Assert.That(info.IsId, Is.True);
        Assert.That(info.IsIdReference, Is.True);
        Assert.That(info.NormalizedValue, Is.EqualTo("42"));
        Assert.That(info.ActualValue, Is.SameAs(actual));
        Assert.That(result.Document, Is.SameAs(document));
        Assert.That(result.SchemaSet, Is.SameAs(set));
        Assert.That(result.Options, Is.SameAs(options));
        Assert.That(result.Validity, Is.EqualTo(XmlSchemaValidity.Invalid));
        Assert.That(result.TypeAnnotations, Is.EqualTo(new XmlSchemaTypeInfo[] { info }));
        Assert.That(result.Diagnostics, Has.Length.EqualTo(1));
        Assert.That(result.Succeeded, Is.True);
    }

    [Test]
    public void XsltDataCarriesPackageCompilationTransformationAndObservabilityState()
    {
        XmlName name = new XmlName();
        name.LocalName = "main";
        XdmSequence value = new XdmSequence();
        XsltPackageReference package = new XsltPackageReference();
        package.Name = name;
        package.Version = "1.2";
        package.LocationUri = "file:///package.xsl";
        package.Visibility = XsltComponentVisibility.Final;
        package.IsOptional = true;
        XsltExtensionBinding extension = new XsltExtensionBinding();
        extension.Name = name;
        extension.BindingKey = "extension";
        extension.MinimumVersion = "1.0";
        extension.IsInstruction = true;
        extension.IsFunction = true;
        XsltParameter parameter = new XsltParameter();
        parameter.Name = name;
        parameter.Value = value;
        parameter.DeclaredType = XdmAtomicType.String;
        parameter.DeclaredOccurrence = XdmOccurrence.OneOrMore;
        parameter.IsTunnel = true;
        parameter.IsStatic = true;
        parameter.IsRequired = true;
        SourceRange range = new SourceRange();
        XsltTraceEvent trace = new XsltTraceEvent();
        trace.Kind = XsltTraceEventKind.EnterTemplate;
        trace.ComponentName = name;
        trace.InstructionName = "xsl:sequence";
        trace.Message = "trace";
        trace.Range = range;
        trace.Depth = 2;
        trace.ContextItem = value;
        XsltMessage message = new XsltMessage();
        message.Text = "message";
        message.Code = name;
        message.Terminate = true;
        message.Range = range;
        message.Content = value;
        XsltStreamabilityReport report = new XsltStreamabilityReport();
        report.Streamability = XsltStreamability.NotStreamable;
        report.Reasons = ["grounded expression"];
        report.Locations = [range];
        report.Modes = [name];
        report.SchemaAware = true;
        XmlSchemaSet schemaSet = new XmlSchemaSet();
        XsltCompileOptions compileOptions = new XsltCompileOptions();
        compileOptions.ConformanceLevel = XsltConformanceLevel.SchemaAware;
        compileOptions.RecoveryPolicy = XsltRecoveryPolicy.Recover;
        compileOptions.BaseUri = "file:///stylesheet.xsl";
        compileOptions.PackageName = name;
        compileOptions.Packages = [package];
        compileOptions.StaticParameters = [parameter];
        compileOptions.Extensions = [extension];
        compileOptions.SchemaSet = schemaSet;
        compileOptions.ResolverPolicy = new XmlResolverPolicy();
        compileOptions.SecurityLimits = new XmlSecurityLimits();
        compileOptions.AnalyzeStreamability = true;
        compileOptions.CompilePackagesSeparately = true;
        object plan = new object();
        XsltExecutable executable = new XsltExecutable();
        executable.PackageName = name;
        executable.PackageVersion = "1.2";
        executable.Plan = plan;
        executable.CompileOptions = compileOptions;
        executable.StreamabilityReport = report;
        executable.Diagnostics = [new XmlDiagnostic()];
        executable.IsImmutable = true;
        executable.IsSchemaAware = true;
        XmlOutput output = new XmlOutput();
        XmlSerializationOptions serialization = new XmlSerializationOptions();
        XsltSecondaryResult secondary = new XsltSecondaryResult();
        secondary.Uri = "file:///secondary.xml";
        secondary.Output = output;
        secondary.SerializationOptions = serialization;
        secondary.Value = value;
        secondary.Disposition = XsltResultDisposition.Commit;
        secondary.Succeeded = true;
        XmlDocument source = new XmlDocument();
        RecordingResolver resolver = new RecordingResolver();
        XsltTransformOptions transformOptions = new XsltTransformOptions();
        transformOptions.Executable = executable;
        transformOptions.SourceDocument = source;
        transformOptions.GlobalContextItem = value;
        transformOptions.InitialMode = name;
        transformOptions.InitialTemplate = name;
        transformOptions.InitialFunction = name;
        transformOptions.Parameters = [parameter];
        transformOptions.PrincipalOutput = output;
        transformOptions.SerializationOptions = serialization;
        transformOptions.RecoveryPolicy = XsltRecoveryPolicy.Recover;
        transformOptions.ResourceResolver = resolver;
        transformOptions.SecurityLimits = new XmlSecurityLimits();
        transformOptions.ResultDisposition = XsltResultDisposition.Pending;
        transformOptions.EnableTracing = true;
        XsltTransformResult result = new XsltTransformResult();
        result.Executable = executable;
        result.Options = transformOptions;
        result.PrincipalValue = value;
        result.PrincipalDocument = new XmlDocument();
        result.SecondaryResults = [secondary];
        result.Messages = [message];
        result.TraceEvents = [trace];
        result.Diagnostics = [new XmlDiagnostic()];
        result.Disposition = XsltResultDisposition.Commit;
        result.Succeeded = true;

        Assert.That(package.Name, Is.SameAs(name));
        Assert.That(package.Version, Is.EqualTo("1.2"));
        Assert.That(package.LocationUri, Is.EqualTo("file:///package.xsl"));
        Assert.That(package.Visibility, Is.EqualTo(XsltComponentVisibility.Final));
        Assert.That(package.IsOptional, Is.True);
        Assert.That(extension.BindingKey, Is.EqualTo("extension"));
        Assert.That(extension.MinimumVersion, Is.EqualTo("1.0"));
        Assert.That(extension.IsInstruction, Is.True);
        Assert.That(extension.IsFunction, Is.True);
        Assert.That(parameter.Value, Is.SameAs(value));
        Assert.That(parameter.DeclaredOccurrence, Is.EqualTo(XdmOccurrence.OneOrMore));
        Assert.That(parameter.IsTunnel, Is.True);
        Assert.That(parameter.IsStatic, Is.True);
        Assert.That(parameter.IsRequired, Is.True);
        Assert.That(trace.Kind, Is.EqualTo(XsltTraceEventKind.EnterTemplate));
        Assert.That(trace.InstructionName, Is.EqualTo("xsl:sequence"));
        Assert.That(trace.Depth, Is.EqualTo(2));
        Assert.That(message.Text, Is.EqualTo("message"));
        Assert.That(message.Terminate, Is.True);
        Assert.That(message.Content, Is.SameAs(value));
        Assert.That(report.Streamability, Is.EqualTo(XsltStreamability.NotStreamable));
