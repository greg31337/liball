        Assert.That(dynamicContext.CurrentDateTime, Is.EqualTo(now));
        Assert.That(dynamicContext.EnvironmentNames, Is.EqualTo(new string[] { "NAME" }));
        Assert.That(dynamicContext.EnvironmentValues, Is.EqualTo(new string[] { "VALUE" }));
        Assert.That(dynamicContext.ResolverPolicy, Is.SameAs(policy));
        Assert.That(dynamicContext.SecurityLimits, Is.SameAs(limits));
        Assert.That(dynamicContext.MaximumOperations, Is.EqualTo(1000));
        Assert.That(compiled.Source, Is.EqualTo("$value"));
