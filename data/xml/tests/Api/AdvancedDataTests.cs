        Assert.That(compileOptions.StaticParameters, Is.EqualTo(new XsltParameter[] { parameter }));
        Assert.That(compileOptions.Extensions, Is.EqualTo(new XsltExtensionBinding[] { extension }));
        Assert.That(compileOptions.SchemaSet, Is.SameAs(schemaSet));
