using System;
using System.Collections.Generic;
using System.IO;
using System.Security.Cryptography;
using System.Text;
using CountryCodes.DataGenerator.Staging;

namespace CountryCodes.DataGenerator.Emission;

internal static class GeneratedMetadataEmitter
{
    private const string FileName = "GeneratedDataMetadata.g.cs";
    private const string HashAlgorithm = "SHA-256";
    private const string HashFormat = "file-name NUL lowercase-sha256 LF; ordinal file-name order";

    internal static GeneratedMetadataEmissionResult Emit(
        SourceManifestInfo manifest,
        IReadOnlyList<string> contentPaths,
        string outputDirectory)
    {
        List<ContentHashEmissionRow> contentHashes = BuildContentHashes(contentPaths);
        string aggregateChecksum = ComputeAggregateChecksum(contentHashes);
        string path = Path.Combine(outputDirectory, FileName);
        Directory.CreateDirectory(outputDirectory);
        File.WriteAllText(
            path,
            Render(manifest, contentHashes, aggregateChecksum),
            new UTF8Encoding(false));
        return new GeneratedMetadataEmissionResult(
            manifest.Sources.Count,
            contentHashes.Count,
            aggregateChecksum,
            path);
    }

    private static List<ContentHashEmissionRow> BuildContentHashes(
        IReadOnlyList<string> contentPaths)
    {
        List<string> paths = new List<string>(contentPaths);
        paths.Sort(ComparePaths);
        List<ContentHashEmissionRow> result = new List<ContentHashEmissionRow>(paths.Count);
        string? previousName = null;
        foreach (string path in paths)
        {
            if (!File.Exists(path))
            {
                throw new EmissionException($"Generated content file does not exist: '{path}'.");
            }

            string name = Path.GetFileName(path);
            if (previousName != null && string.Equals(previousName, name, StringComparison.Ordinal))
            {
                throw new EmissionException($"Duplicate generated content file name '{name}'.");
            }

            byte[] bytes = File.ReadAllBytes(path);
            result.Add(new ContentHashEmissionRow(name, LowerHex(SHA256.HashData(bytes))));
            previousName = name;
        }

        if (result.Count == 0)
        {
            throw new EmissionException("Generated metadata has no content files to hash.");
        }

        return result;
    }

    private static string ComputeAggregateChecksum(
        IReadOnlyList<ContentHashEmissionRow> contentHashes)
    {
        StringBuilder payload = new StringBuilder(contentHashes.Count * 96);
        foreach (ContentHashEmissionRow row in contentHashes)
        {
            payload.Append(row.FileName);
            payload.Append('\0');
            payload.Append(row.Sha256);
            payload.Append('\n');
        }

        return LowerHex(SHA256.HashData(Encoding.UTF8.GetBytes(payload.ToString())));
    }

    private static int ComparePaths(string left, string right)
    {
        return string.CompareOrdinal(Path.GetFileName(left), Path.GetFileName(right));
    }

    private static string LowerHex(byte[] bytes)
    {
        return Convert.ToHexString(bytes).ToLowerInvariant();
    }

    private static string Render(
        SourceManifestInfo manifest,
        IReadOnlyList<ContentHashEmissionRow> contentHashes,
        string aggregateChecksum)
    {
        StringBuilder builder = new StringBuilder(12_000);
        Line(builder, "// <auto-generated />");
        Line(builder, "namespace countrycodes;");
        Line(builder, string.Empty);
        RenderTypes(builder);
        Line(builder, string.Empty);
        Line(builder, "internal static class GeneratedDataMetadata");
        Line(builder, "{");
        Line(builder, $"    internal const string SchemaVersion = {Literal(manifest.DatasetSchemaVersion)};");
        Line(builder, $"    internal const string DataVersion = {Literal(manifest.DataVersion)};");
        Line(builder, $"    internal const string EffectiveDate = {Literal(manifest.EffectiveDate)};");
        Line(builder, $"    internal const string GeneratorVersion = {Literal(manifest.GeneratorVersion)};");
        Line(builder, $"    internal const string ContentChecksumAlgorithm = {Literal(HashAlgorithm)};");
        Line(builder, $"    internal const string ContentChecksumFormat = {Literal(HashFormat)};");
        Line(builder, $"    internal const string AggregateContentChecksum = {Literal(aggregateChecksum)};");
        RenderSourceRevisions(builder, manifest.Sources);
        RenderContentHashes(builder, contentHashes);
        Line(builder, "}");
        return builder.ToString();
    }

    private static void RenderTypes(StringBuilder builder)
    {
        Line(builder, "internal class GeneratedSourceRevisionRow");
        Line(builder, "{");
        Line(builder, "    internal string SourceId;");
        Line(builder, "    internal string Revision;");
        Line(builder, "    internal string RetrievedOn;");
        Line(builder, string.Empty);
        Line(builder, "    internal GeneratedSourceRevisionRow(");
        Line(builder, "        string sourceId,");
        Line(builder, "        string revision,");
        Line(builder, "        string retrievedOn)");
        Line(builder, "    {");
        Line(builder, "        SourceId = sourceId;");
        Line(builder, "        Revision = revision;");
        Line(builder, "        RetrievedOn = retrievedOn;");
        Line(builder, "    }");
        Line(builder, "}");
        Line(builder, string.Empty);
        Line(builder, "internal class GeneratedContentHashRow");
        Line(builder, "{");
        Line(builder, "    internal string FileName;");
        Line(builder, "    internal string Sha256;");
        Line(builder, string.Empty);
        Line(builder, "    internal GeneratedContentHashRow(string fileName, string sha256)");
        Line(builder, "    {");
        Line(builder, "        FileName = fileName;");
        Line(builder, "        Sha256 = sha256;");
        Line(builder, "    }");
        Line(builder, "}");
    }

    private static void RenderSourceRevisions(
        StringBuilder builder,
        IReadOnlyList<SourceSnapshotInfo> sources)
    {
        Line(builder, string.Empty);
        Line(builder, "    internal static readonly GeneratedSourceRevisionRow[] SourceRevisions =");
        Line(builder, "    {");
        foreach (SourceSnapshotInfo source in sources)
        {
            Line(builder, "        new GeneratedSourceRevisionRow(");
            Line(builder, $"            {Literal(source.Id)},");
            Line(builder, $"            {Literal(source.Revision)},");
            Line(builder, $"            {Literal(source.RetrievedOn)}),");
        }

        Line(builder, "    };");
    }

    private static void RenderContentHashes(
        StringBuilder builder,
        IReadOnlyList<ContentHashEmissionRow> contentHashes)
    {
        Line(builder, string.Empty);
        Line(builder, "    internal static readonly GeneratedContentHashRow[] ContentHashes =");
        Line(builder, "    {");
        foreach (ContentHashEmissionRow row in contentHashes)
        {
            Line(builder, "        new GeneratedContentHashRow(");
            Line(builder, $"            {Literal(row.FileName)},");
            Line(builder, $"            {Literal(row.Sha256)}),");
        }

        Line(builder, "    };");
    }

    private static string Literal(string value)
    {
        return "\"" + value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal)
            .Replace("\r", "\\r", StringComparison.Ordinal)
            .Replace("\n", "\\n", StringComparison.Ordinal)
            .Replace("\t", "\\t", StringComparison.Ordinal) + "\"";
    }

    private static void Line(StringBuilder builder, string value)
    {
        builder.Append(value);
        builder.Append('\n');
    }

    private sealed class ContentHashEmissionRow
    {
        internal ContentHashEmissionRow(string fileName, string sha256)
        {
            FileName = fileName;
            Sha256 = sha256;
        }

        internal string FileName { get; }

        internal string Sha256 { get; }
    }
}
