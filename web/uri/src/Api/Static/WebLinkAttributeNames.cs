namespace uri;

/// <summary>
/// Provides the standard Web Link parameter names defined by RFC 8288.
/// </summary>
public static class WebLinkAttributeNames
{
    /// <summary>The anchor parameter name.</summary>
    public const string Anchor = "anchor";

    /// <summary>The target language parameter name.</summary>
    public const string HrefLang = "hreflang";

    /// <summary>The destination media parameter name.</summary>
    public const string Media = "media";

    /// <summary>The forward relation parameter name.</summary>
    public const string Rel = "rel";

    /// <summary>The reverse relation parameter name.</summary>
    public const string Rev = "rev";

    /// <summary>The human-readable title parameter name.</summary>
    public const string Title = "title";

    /// <summary>The RFC 8187 extended title parameter name.</summary>
    public const string TitleExtended = "title*";

    /// <summary>The media type parameter name.</summary>
    public const string Type = "type";
}
