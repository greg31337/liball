namespace sdp;

/// <summary>
/// Defines registered SDP network-type tokens.
/// </summary>
public static class SdpNetworkTypes
{
    /// <summary>The Internet network token.</summary>
    public const string Internet = "IN";

    /// <summary>The telephony network token.</summary>
    public const string Telephony = "TN";

    /// <summary>The Asynchronous Transfer Mode network token.</summary>
    public const string Atm = "ATM";

    /// <summary>The public switched telephone network token.</summary>
    public const string PublicSwitchedTelephoneNetwork = "PSTN";
}
