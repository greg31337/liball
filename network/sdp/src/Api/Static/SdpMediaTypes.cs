namespace sdp;

/// <summary>
/// Defines registered SDP media tokens commonly used by applications.
/// </summary>
public static class SdpMediaTypes
{
    /// <summary>The audio media token.</summary>
    public const string Audio = "audio";

    /// <summary>The video media token.</summary>
    public const string Video = "video";

    /// <summary>The text media token.</summary>
    public const string Text = "text";

    /// <summary>The application media token.</summary>
    public const string Application = "application";

    /// <summary>The message media token.</summary>
    public const string Message = "message";

    /// <summary>The image media token.</summary>
    public const string Image = "image";

    /// <summary>The haptics media token.</summary>
    public const string Haptics = "haptics";
}
