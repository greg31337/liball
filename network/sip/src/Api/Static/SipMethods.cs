namespace sip;

/// <summary>
/// Provides standard SIP request-method tokens.
/// </summary>
public static class SipMethods
{
    /// <summary>The ACK method token.</summary>
    public const string Ack = "ACK";

    /// <summary>The BYE method token.</summary>
    public const string Bye = "BYE";

    /// <summary>The CANCEL method token.</summary>
    public const string Cancel = "CANCEL";

    /// <summary>The INFO method token.</summary>
    public const string Info = "INFO";

    /// <summary>The INVITE method token.</summary>
    public const string Invite = "INVITE";

    /// <summary>The MESSAGE method token.</summary>
    public const string Message = "MESSAGE";

    /// <summary>The NOTIFY method token.</summary>
    public const string Notify = "NOTIFY";

    /// <summary>The OPTIONS method token.</summary>
    public const string Options = "OPTIONS";

    /// <summary>The PRACK method token.</summary>
    public const string Prack = "PRACK";

    /// <summary>The PUBLISH method token.</summary>
    public const string Publish = "PUBLISH";

    /// <summary>The REFER method token.</summary>
    public const string Refer = "REFER";

    /// <summary>The REGISTER method token.</summary>
    public const string Register = "REGISTER";

    /// <summary>The SUBSCRIBE method token.</summary>
    public const string Subscribe = "SUBSCRIBE";

    /// <summary>The UPDATE method token.</summary>
    public const string Update = "UPDATE";
}
