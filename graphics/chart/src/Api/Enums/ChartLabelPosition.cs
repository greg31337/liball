namespace chart;
/// <summary>
/// Specifies the supported label position values.
/// </summary>
public enum ChartLabelPosition
{
    /// <summary>
    /// Uses the center option for the label position.
    /// </summary>
    Center = 0,
    /// <summary>
    /// Uses the above option for the label position.
    /// </summary>
    Above = 1,
    /// <summary>
    /// Uses the below option for the label position.
    /// </summary>
    Below = 2,
    /// <summary>
    /// Uses the left option for the label position.
    /// </summary>
    Left = 3,
    /// <summary>
    /// Uses the right option for the label position.
    /// </summary>
    Right = 4
}
