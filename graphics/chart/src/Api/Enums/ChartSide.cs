namespace chart;
/// <summary>
/// Specifies the supported side values.
/// </summary>
public enum ChartSide
{
    /// <summary>
    /// Uses the left option for the side.
    /// </summary>
    Left = 0,
    /// <summary>
    /// Uses the right option for the side.
    /// </summary>
    Right = 1,
    /// <summary>
    /// Uses the top option for the side.
    /// </summary>
    Top = 2,
    /// <summary>
    /// Uses the bottom option for the side.
    /// </summary>
    Bottom = 3
}
