namespace chart;
/// <summary>
/// Specifies the supported stack mode values.
/// </summary>
public enum ChartStackMode
{
    /// <summary>
    /// Uses the none option for the stack mode.
    /// </summary>
    None = 0,
    /// <summary>
    /// Uses the zero option for the stack mode.
    /// </summary>
    Zero = 1,
    /// <summary>
    /// Uses the percent option for the stack mode.
    /// </summary>
    Percent = 2,
    /// <summary>
    /// Uses the diverging option for the stack mode.
    /// </summary>
    Diverging = 3,
    /// <summary>
    /// Uses the streamgraph option for the stack mode.
    /// </summary>
    Streamgraph = 4
}
