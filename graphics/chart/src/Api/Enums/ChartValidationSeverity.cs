namespace chart;
/// <summary>
/// Specifies the supported validation severity values.
/// </summary>
public enum ChartValidationSeverity
{
    /// <summary>
    /// Uses the warning option for the validation severity.
    /// </summary>
    Warning = 0,
    /// <summary>
    /// Uses the error option for the validation severity.
    /// </summary>
    Error = 1
}
