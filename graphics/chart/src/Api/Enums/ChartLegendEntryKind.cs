namespace chart;
/// <summary>
/// Specifies the supported legend entry kind values.
/// </summary>
public enum ChartLegendEntryKind
{
    /// <summary>
    /// Uses the symbol option for the legend entry kind.
    /// </summary>
    Symbol = 0,
    /// <summary>
    /// Uses the gradient option for the legend entry kind.
    /// </summary>
    Gradient = 1,
    /// <summary>
    /// Uses the custom option for the legend entry kind.
    /// </summary>
    Custom = 2
}
