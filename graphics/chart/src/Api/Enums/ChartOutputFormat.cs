namespace chart;
/// <summary>
/// Specifies the supported output format values.
/// </summary>
public enum ChartOutputFormat
{
    /// <summary>
    /// Uses the raw bitmap option for the output format.
    /// </summary>
    RawBitmap = 0,
    /// <summary>
    /// Uses the bmp option for the output format.
    /// </summary>
    Bmp = 1,
    /// <summary>
    /// Uses the png option for the output format.
    /// </summary>
    Png = 2,
    /// <summary>
    /// Uses the svg option for the output format.
    /// </summary>
    Svg = 3
}
