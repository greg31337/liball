namespace chart;
/// <summary>
/// Specifies the supported layout item kind values.
/// </summary>
public enum ChartLayoutItemKind
{
    /// <summary>
    /// Uses the figure option for the layout item kind.
    /// </summary>
    Figure = 0,
    /// <summary>
    /// Uses the content option for the layout item kind.
    /// </summary>
    Content = 1,
    /// <summary>
    /// Uses the plot option for the layout item kind.
    /// </summary>
    Plot = 2,
    /// <summary>
    /// Uses the axis option for the layout item kind.
    /// </summary>
    Axis = 3,
    /// <summary>
    /// Uses the title option for the layout item kind.
    /// </summary>
    Title = 4,
    /// <summary>
    /// Uses the subtitle option for the layout item kind.
    /// </summary>
    Subtitle = 5,
    /// <summary>
    /// Uses the caption option for the layout item kind.
    /// </summary>
    Caption = 6,
    /// <summary>
    /// Uses the legend option for the layout item kind.
    /// </summary>
    Legend = 7,
    /// <summary>
    /// Uses the colorbar option for the layout item kind.
    /// </summary>
    Colorbar = 8,
    /// <summary>
    /// Uses the annotation option for the layout item kind.
    /// </summary>
    Annotation = 9
}
