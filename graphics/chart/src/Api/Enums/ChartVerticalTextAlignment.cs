namespace chart;
/// <summary>
/// Specifies the supported vertical text alignment values.
/// </summary>
public enum ChartVerticalTextAlignment
{
    /// <summary>
    /// Uses the top option for the vertical text alignment.
    /// </summary>
    Top = 0,
    /// <summary>
    /// Uses the middle option for the vertical text alignment.
    /// </summary>
    Middle = 1,
    /// <summary>
    /// Uses the baseline option for the vertical text alignment.
    /// </summary>
    Baseline = 2,
    /// <summary>
    /// Uses the bottom option for the vertical text alignment.
    /// </summary>
    Bottom = 3
}
