namespace chart;
/// <summary>
/// Specifies the supported fill rule values.
/// </summary>
public enum ChartFillRule
{
    /// <summary>
    /// Uses the nonzero option for the fill rule.
    /// </summary>
    Nonzero = 0,
    /// <summary>
    /// Uses the even odd option for the fill rule.
    /// </summary>
    EvenOdd = 1
}
