namespace chart;
/// <summary>
/// Specifies the supported data kind values.
/// </summary>
public enum ChartDataKind
{
    /// <summary>
    /// Uses the number option for the data kind.
    /// </summary>
    Number = 0,
    /// <summary>
    /// Uses the text option for the data kind.
    /// </summary>
    Text = 1,
    /// <summary>
    /// Uses the date time option for the data kind.
    /// </summary>
    DateTime = 2,
    /// <summary>
    /// Uses the category option for the data kind.
    /// </summary>
    Category = 3,
    /// <summary>
    /// Uses the matrix option for the data kind.
    /// </summary>
    Matrix = 4
}
