namespace chart;
/// <summary>
/// Specifies the supported marker shape values.
/// </summary>
public enum ChartMarkerShape
{
    /// <summary>
    /// Uses the circle option for the marker shape.
    /// </summary>
    Circle = 0,
    /// <summary>
    /// Uses the square option for the marker shape.
    /// </summary>
    Square = 1,
    /// <summary>
    /// Uses the diamond option for the marker shape.
    /// </summary>
    Diamond = 2,
    /// <summary>
    /// Uses the triangle option for the marker shape.
    /// </summary>
    Triangle = 3,
    /// <summary>
    /// Uses the cross option for the marker shape.
    /// </summary>
    Cross = 4,
    /// <summary>
    /// Uses the plus option for the marker shape.
    /// </summary>
    Plus = 5,
    /// <summary>
    /// Uses the star option for the marker shape.
    /// </summary>
    Star = 6,
    /// <summary>
    /// Uses the line option for the marker shape.
    /// </summary>
    Line = 7,
    /// <summary>
    /// Uses the custom path option for the marker shape.
    /// </summary>
    CustomPath = 8
}
