namespace chart;
/// <summary>
/// Specifies the supported axis placement values.
/// </summary>
public enum ChartAxisPlacement
{
    /// <summary>
    /// Uses the bottom option for the axis placement.
    /// </summary>
    Bottom = 0,
    /// <summary>
    /// Uses the top option for the axis placement.
    /// </summary>
    Top = 1,
    /// <summary>
    /// Uses the left option for the axis placement.
    /// </summary>
    Left = 2,
    /// <summary>
    /// Uses the right option for the axis placement.
    /// </summary>
    Right = 3,
    /// <summary>
    /// Uses the inside option for the axis placement.
    /// </summary>
    Inside = 4,
    /// <summary>
    /// Uses the outside option for the axis placement.
    /// </summary>
    Outside = 5
}
