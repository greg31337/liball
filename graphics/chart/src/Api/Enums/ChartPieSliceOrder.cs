namespace chart;
/// <summary>
/// Specifies the supported pie slice order values.
/// </summary>
public enum ChartPieSliceOrder
{
    /// <summary>
    /// Uses the original option for the pie slice order.
    /// </summary>
    Original = 0,
    /// <summary>
    /// Uses the ascending option for the pie slice order.
    /// </summary>
    Ascending = 1,
    /// <summary>
    /// Uses the descending option for the pie slice order.
    /// </summary>
    Descending = 2
}
