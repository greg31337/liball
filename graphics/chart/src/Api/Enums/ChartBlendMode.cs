namespace chart;
/// <summary>
/// Specifies the supported blend mode values.
/// </summary>
public enum ChartBlendMode
{
    /// <summary>
    /// Uses the normal option for the blend mode.
    /// </summary>
    Normal = 0,
    /// <summary>
    /// Uses the source over option for the blend mode.
    /// </summary>
    SourceOver = 1,
    /// <summary>
    /// Uses the source option for the blend mode.
    /// </summary>
    Source = 2,
    /// <summary>
    /// Uses the multiply option for the blend mode.
    /// </summary>
    Multiply = 3,
    /// <summary>
    /// Uses the screen option for the blend mode.
    /// </summary>
    Screen = 4,
    /// <summary>
    /// Uses the darken option for the blend mode.
    /// </summary>
    Darken = 5,
    /// <summary>
    /// Uses the lighten option for the blend mode.
    /// </summary>
    Lighten = 6
}
