namespace chart;
/// <summary>
/// Specifies the supported cartesian series kind values.
/// </summary>
public enum ChartCartesianSeriesKind
{
    /// <summary>
    /// Uses the line option for the cartesian series kind.
    /// </summary>
    Line = 0,
    /// <summary>
    /// Uses the scatter option for the cartesian series kind.
    /// </summary>
    Scatter = 1,
    /// <summary>
    /// Uses the area option for the cartesian series kind.
    /// </summary>
    Area = 2,
    /// <summary>
    /// Uses the bar option for the cartesian series kind.
    /// </summary>
    Bar = 3,
    /// <summary>
    /// Uses the mixed option for the cartesian series kind.
    /// </summary>
    Mixed = 4
}
