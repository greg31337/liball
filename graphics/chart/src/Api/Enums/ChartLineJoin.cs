namespace chart;
/// <summary>
/// Specifies the supported line join values.
/// </summary>
public enum ChartLineJoin
{
    /// <summary>
    /// Uses the miter option for the line join.
    /// </summary>
    Miter = 0,
    /// <summary>
    /// Uses the bevel option for the line join.
    /// </summary>
    Bevel = 1,
    /// <summary>
    /// Uses the round option for the line join.
    /// </summary>
    Round = 2
}
