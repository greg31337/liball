namespace chart;
/// <summary>
/// Specifies the supported text alignment values.
/// </summary>
public enum ChartTextAlignment
{
    /// <summary>
    /// Uses the left option for the text alignment.
    /// </summary>
    Left = 0,
    /// <summary>
    /// Uses the center option for the text alignment.
    /// </summary>
    Center = 1,
    /// <summary>
    /// Uses the right option for the text alignment.
    /// </summary>
    Right = 2,
    /// <summary>
    /// Uses the start option for the text alignment.
    /// </summary>
    Start = 3,
    /// <summary>
    /// Uses the middle option for the text alignment.
    /// </summary>
    Middle = 4,
    /// <summary>
    /// Uses the end option for the text alignment.
    /// </summary>
    End = 5
}
