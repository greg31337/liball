namespace chart;
/// <summary>
/// Specifies the supported line cap values.
/// </summary>
public enum ChartLineCap
{
    /// <summary>
    /// Uses the butt option for the line cap.
    /// </summary>
    Butt = 0,
    /// <summary>
    /// Uses the square option for the line cap.
    /// </summary>
    Square = 1,
    /// <summary>
    /// Uses the round option for the line cap.
    /// </summary>
    Round = 2
}
