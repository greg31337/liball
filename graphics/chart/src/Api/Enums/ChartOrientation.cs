namespace chart;
/// <summary>
/// Specifies the supported orientation values.
/// </summary>
public enum ChartOrientation
{
    /// <summary>
    /// Uses the horizontal option for the orientation.
    /// </summary>
    Horizontal = 0,
    /// <summary>
    /// Uses the vertical option for the orientation.
    /// </summary>
    Vertical = 1,
    /// <summary>
    /// Uses the radial option for the orientation.
    /// </summary>
    Radial = 2
}
