namespace chart;
/// <summary>Defines supported BMP output bit depths.</summary>
public enum ChartBmpBitDepth
{
    /// <summary>Eight-bit indexed pixels with a color table.</summary>
    Indexed8 = 8,
    /// <summary>Twenty-four-bit BGR pixels.</summary>
    Rgb24 = 24,
    /// <summary>Thirty-two-bit BGRA pixels.</summary>
    Rgba32 = 32
}
