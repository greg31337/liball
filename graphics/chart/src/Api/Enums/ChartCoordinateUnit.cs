namespace chart;
/// <summary>
/// Specifies the supported coordinate unit values.
/// </summary>
public enum ChartCoordinateUnit
{
    /// <summary>
    /// Uses the pixel option for the coordinate unit.
    /// </summary>
    Pixel = 0,
    /// <summary>
    /// Uses the plot option for the coordinate unit.
    /// </summary>
    Plot = 1,
    /// <summary>
    /// Uses the paper option for the coordinate unit.
    /// </summary>
    Paper = 2,
    /// <summary>
    /// Uses the data option for the coordinate unit.
    /// </summary>
    Data = 3,
    /// <summary>
    /// Uses the axis option for the coordinate unit.
    /// </summary>
    Axis = 4,
    /// <summary>
    /// Uses the fraction option for the coordinate unit.
    /// </summary>
    Fraction = 5
}
