namespace chart;
/// <summary>
/// Specifies the supported axis kind values.
/// </summary>
public enum ChartAxisKind
{
    /// <summary>
    /// Uses the x option for the axis kind.
    /// </summary>
    X = 0,
    /// <summary>
    /// Uses the y option for the axis kind.
    /// </summary>
    Y = 1,
    /// <summary>
    /// Uses the radial option for the axis kind.
    /// </summary>
    Radial = 2,
    /// <summary>
    /// Uses the angular option for the axis kind.
    /// </summary>
    Angular = 3,
    /// <summary>
    /// Uses the ternary option for the axis kind.
    /// </summary>
    Ternary = 4
}
