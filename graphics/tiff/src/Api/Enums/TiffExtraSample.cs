namespace tiff;

/// <summary>Specifies the supported extra sample values used by TIFF data.</summary>
public enum TiffExtraSample
{
    /// <summary>Specifies unspecified.</summary>
    Unspecified = 0,
    /// <summary>Specifies associated alpha.</summary>
    AssociatedAlpha = 1,
    /// <summary>Specifies unassociated alpha.</summary>
    UnassociatedAlpha = 2
}
