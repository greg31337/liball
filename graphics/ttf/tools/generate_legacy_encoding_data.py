BASE_URL = "https://www.unicode.org/Public/MAPPINGS/VENDORS/"
TRANSCODING_HINT_START = 0xF860
TRANSCODING_HINT_END = 0xF87F


def download(relative_url):
    with urllib.request.urlopen(BASE_URL + relative_url) as response:
        return response.read()


def parse_mapping(data):
    mappings = {value: value for value in range(0x20)}
    mappings[0x7F] = 0x7F

    for raw_line in data.decode("utf-8", errors="replace").splitlines():
        body = raw_line.split("#", 1)[0].strip()
        columns = body.split()
        if len(columns) < 2 or not columns[0].startswith("0x"):
            continue

        encoded_value = int(columns[0], 16)
        unicode_values = [
            int(value, 16)
            for value in re.findall(r"0x([0-9A-Fa-f]+)", " ".join(columns[1:]))
        ]
        unicode_values = [
            value
            for value in unicode_values
            if not TRANSCODING_HINT_START <= value <= TRANSCODING_HINT_END
        ]

        if not unicode_values:
            continue

        unicode_value = unicode_values[0]
        if encoded_value > 0xFFFF or unicode_value > 0xFFFF:
            raise ValueError("Legacy mapping value does not fit the packed format")
        mappings[encoded_value] = unicode_value

    return sorted(mappings.items())


def encode_mapping(mappings):
    raw = b"".join(struct.pack(">HH", encoded, unicode) for encoded, unicode in mappings)
    compressed = bytearray(gzip.compress(raw, compresslevel=9, mtime=0))
    compressed[9] = 255
    return base64.b64encode(compressed).decode("ascii")


def append_wrapped_string(lines, value):
    lines.append("        new string[]")
    lines.append("        {")
    for index in range(0, len(value), 100):
        suffix = "," if index + 100 < len(value) else ""
        lines.append(f'            "{value[index:index + 100]}"{suffix}')
    lines.append("        });")


def generate(output_path):
    encoded_sources = []
    source_comments = []

    for code_page, relative_url, expected_hash in SOURCES:
        data = download(relative_url)
        actual_hash = hashlib.sha256(data).hexdigest()
        if actual_hash != expected_hash:
            raise ValueError(
                f"SHA-256 mismatch for {relative_url}: {actual_hash} != {expected_hash}"
            )
        encoded_sources.append((code_page, encode_mapping(parse_mapping(data))))
        source_comments.append(
            f"// {BASE_URL}{relative_url} SHA-256 {expected_hash}"
        )

    lines = [
        "namespace ttf;",
        "",
        "// Generated by tools/generate_legacy_encoding_data.py.",
        "// Unicode Consortium vendor mapping sources:",
        *source_comments,
        "internal static class LegacyEncodingTables",
        "{",
    ]

    for code_page, encoded_data in encoded_sources:
        lines.append(
            f"    static LegacyEncodingMap codePage{code_page} = new LegacyEncodingMap("
        )
        append_wrapped_string(lines, encoded_data)
        lines.append("")

    lines.extend(
        [
            "    internal static LegacyEncodingMap GetMap(int codePage)",
            "    {",
        ]
    )
    for code_page, _ in encoded_sources:
        lines.extend(
            [
                f"        if (codePage == {code_page})",
                "        {",
                f"            return codePage{code_page};",
                "        }",
                "",
            ]
        )
    lines.extend(["        return null;", "    }", "}", ""])
    output_path.write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("src/Encodings/LegacyEncodingData.Generated.cs"),
    )
    arguments = parser.parse_args()
    generate(arguments.output)


if __name__ == "__main__":
    main()
