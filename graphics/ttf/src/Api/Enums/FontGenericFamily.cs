namespace ttf;

/// <summary>Identifies a caller-configured generic font family.</summary>
public enum FontGenericFamily
{
    /// <summary>The generic serif family.</summary>
    Serif = 0,

    /// <summary>The generic sans-serif family.</summary>
    SansSerif = 1,

    /// <summary>The generic fixed-pitch family.</summary>
    Monospace = 2,

    /// <summary>The generic cursive family.</summary>
    Cursive = 3,

    /// <summary>The generic fantasy family.</summary>
    Fantasy = 4,

    /// <summary>The generic user-interface family.</summary>
    SystemUi = 5,

    /// <summary>The generic emoji family.</summary>
    Emoji = 6,

    /// <summary>The generic mathematical family.</summary>
    Math = 7,

    /// <summary>The generic Chinese FangSong family.</summary>
    FangSong = 8
}
