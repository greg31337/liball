namespace ttf;

/// <summary>Identifies the requested upright or slanted font style.</summary>
public enum FontStyle
{
    /// <summary>Requests an upright face.</summary>
    Normal = 0,

    /// <summary>Requests a designed italic face.</summary>
    Italic = 1,

    /// <summary>Requests a designed oblique face.</summary>
    Oblique = 2
}
