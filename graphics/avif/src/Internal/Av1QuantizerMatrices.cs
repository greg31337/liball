    static readonly byte[] matrixData = LoadData();

    internal static byte[] GetMatrix(
        int level,
        int planeType,
        Av1TransformSize transformSize)
    {
        int transformIndex = (int)transformSize;
        Av1TransformSize adjusted =
            Av1ConversionTables.GetAdjustedTransformSize(transformSize);
        int count = Av1ConversionTables.GetTransformCoefficientCount(adjusted);
        if (level < 0
            || level >= Av1SyntaxConstants.NumQuantizerMatrixLevels
            || planeType < 0
            || planeType > 1
            || transformIndex < 0
            || transformIndex >= matrixOffsets.Length
            || count == 0)
        {
            return System.Array.Empty<byte>();
        }

        byte[] matrix = new byte[count];
        if (level == Av1SyntaxConstants.NumQuantizerMatrixLevels - 1)
        {
            System.Array.Fill(matrix, (byte)32);
            return matrix;
        }

        int sourceOffset =
            (level * 2 + planeType) * Av1SyntaxConstants.QuantizerMatrixTotalSize
            + matrixOffsets[transformIndex];
        System.Array.Copy(matrixData, sourceOffset, matrix, 0, count);
        return matrix;
    }

    internal static int GetWeight(
        int level,
        int planeType,
        Av1TransformSize transformSize,
        int row,
        int column)
    {
        Av1TransformSize adjusted =
            Av1ConversionTables.GetAdjustedTransformSize(transformSize);
        int width = Av1ConversionTables.GetTransformWidth(adjusted);
        int height = Av1ConversionTables.GetTransformHeight(adjusted);
        if (row < 0 || row >= height || column < 0 || column >= width)
        {
            return 0;
        }

        byte[] matrix = GetMatrix(level, planeType, transformSize);
        return matrix.Length == 0 ? 0 : matrix[row * width + column];
    }

    internal static int GetMatrixOffset(Av1TransformSize transformSize)
    {
        int index = (int)transformSize;
        return index >= 0 && index < matrixOffsets.Length
            ? matrixOffsets[index]
            : -1;
    }

    static byte[] LoadData()
    {
        byte[] compressed = System.Convert.FromBase64String(JoinChunks());
        System.IO.MemoryStream input = new System.IO.MemoryStream(compressed);
        System.IO.MemoryStream output = new System.IO.MemoryStream();
        using (System.IO.Compression.GZipStream gzip =
            new System.IO.Compression.GZipStream(
                input,
                System.IO.Compression.CompressionMode.Decompress))
        {
            gzip.CopyTo(output);
        }

        byte[] data = output.ToArray();
        input.Close();
        output.Close();
        return data;
    }

    static string JoinChunks()
    {
        System.Text.StringBuilder builder = new System.Text.StringBuilder();
        int index = 0;
        while (index < compressedChunks.Length)
        {
            builder.Append(compressedChunks[index]);
            index++;
        }

        return builder.ToString();
    }
