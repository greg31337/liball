using System;
using System.Globalization;

namespace avif;

/// <summary>Parses, generates, and reconciles public AV1 codec signaling models.</summary>
public class Av1CodecConfigurationCodec : IAv1CodecConfigurationCodec, IAvifDiagnosticSource
{
    AvifResultCode code;

    /// <summary>Creates an AV1 codec signaling service in the successful state.</summary>
    public Av1CodecConfigurationCodec()
    {
        code = AvifResultCode.Success;
    }

    /// <summary>Returns the outcome of the most recent operation.</summary>
    /// <returns>The stable result code.</returns>
    public AvifResultCode GetCode()
    {
        return code;
    }

    /// <summary>Returns diagnostics for the most recent AV1 signaling operation.</summary>
    /// <returns>The structured AV1 diagnostics.</returns>
    public AvifDiagnosticReport GetDiagnostics()
    {
        return AvifDiagnosticReport.FromCode(
            code,
            AvifDiagnosticCategory.Av1,
            "The AV1 codec-signaling operation did not complete successfully.");
    }

    /// <summary>Parses an AV1 codec configuration record payload without its ISO box header.</summary>
    /// <param name="source">The complete record beginning with marker and version fields.</param>
    /// <returns>The parsed configuration or a model carrying the failure code.</returns>
    public Av1CodecConfiguration ParseConfigurationRecord(
        ReadOnlySpan<byte> source)
    {
        Av1ItemConfigurationParseResult parsed =
            Av1ItemConfigurationBox.ParsePayload(source);
        code = parsed.Code;
        if (code != AvifResultCode.Success || parsed.Configuration == null)
        {
            return CreateConfigurationFailure(code);
        }
        return CreatePublicConfiguration(parsed.Configuration);
    }

    /// <summary>Generates an AV1 codec configuration record payload without an ISO box header.</summary>
    /// <param name="configuration">The configuration fields and optional configuration OBUs.</param>
    /// <returns>The generated bytes or a stable failure result.</returns>
    public AvifEncodeResult GenerateConfigurationRecord(
        Av1CodecConfiguration configuration)
    {
        AvifEncodeResult result = CreateConfigurationBytes(configuration);
        code = result.GetCode();
        return result;
    }

    /// <summary>Parses an AV1 RFC 6381 codecs parameter string.</summary>
    /// <param name="source">The complete abbreviated or expanded codecs parameter.</param>
    /// <returns>The parsed parameters or a model carrying the failure code.</returns>
    public Av1CodecParameters ParseCodecString(string? source)
    {
        Av1CodecParameters result = new Av1CodecParameters();
        if (source == null)
        {
            return SetParameterFailure(result, AvifResultCode.InvalidArgument);
        }
        string[] fields = source.Split('.');
        if (fields.Length != 4 && fields.Length != 10
            || fields[0] != "av01"
            || fields[1].Length != 1
            || fields[2].Length != 3
            || fields[3].Length != 2)
        {
            return SetParameterFailure(result, AvifResultCode.InvalidArgument);
        }
        result.Profile = ParseFixedDecimal(fields[1], 1);
        result.Level = ParseFixedDecimal(fields[2].Substring(0, 2), 2);
        result.Tier = fields[2][2] == 'M'
            ? 0 : fields[2][2] == 'H' ? 1 : -1;
        result.BitDepth = ParseFixedDecimal(fields[3], 2);
        if (fields.Length == 10)
        {
            if (fields[4].Length != 1 || fields[5].Length != 3
                || fields[6].Length != 2 || fields[7].Length != 2
                || fields[8].Length != 2 || fields[9].Length != 1)
            {
                return SetParameterFailure(result, AvifResultCode.InvalidArgument);
            }
            int monochrome = ParseFixedDecimal(fields[4], 1);
            int subsamplingX = ParseFixedDecimal(fields[5].Substring(0, 1), 1);
            int subsamplingY = ParseFixedDecimal(fields[5].Substring(1, 1), 1);
            int chromaPosition = ParseFixedDecimal(fields[5].Substring(2, 1), 1);
            int range = ParseFixedDecimal(fields[9], 1);
            if (monochrome < 0 || subsamplingX < 0 || subsamplingY < 0
                || chromaPosition < 0 || range < 0
                || monochrome > 1 || subsamplingX > 1 || subsamplingY > 1
                || chromaPosition > 2 || range > 1)
            {
                return SetParameterFailure(result, AvifResultCode.InvalidArgument);
            }
            result.Monochrome = monochrome == 1;
            result.ChromaSubsamplingX = subsamplingX == 1;
            result.ChromaSubsamplingY = subsamplingY == 1;
            result.ChromaSamplePosition = (AvifChromaSamplePosition)chromaPosition;
            result.ColorPrimaries = ParseFixedDecimal(fields[6], 2);
            result.TransferCharacteristics = ParseFixedDecimal(fields[7], 2);
            result.MatrixCoefficients = ParseFixedDecimal(fields[8], 2);
            result.Range = range == 1 ? AvifRange.Full : AvifRange.Limited;
            result.HasOptionalFields = true;
        }
        code = ValidateParameters(result);
        result.Code = code;
        return result;
    }

    /// <summary>Generates an abbreviated or expanded AV1 RFC 6381 codecs parameter string.</summary>
    /// <param name="parameters">The parameters to validate and serialize.</param>
    /// <returns>The codec string, or an empty string on failure.</returns>
    public string GenerateCodecString(Av1CodecParameters parameters)
    {
        code = ValidateParameters(parameters);
        if (code != AvifResultCode.Success)
        {
            return string.Empty;
        }
        string tier = parameters.Tier == 0 ? "M" : "H";
        string result = parameters.SampleEntry
            + "." + parameters.Profile.ToString(CultureInfo.InvariantCulture)
            + "." + FormatTwoDigits(parameters.Level) + tier
            + "." + FormatTwoDigits(parameters.BitDepth);
        if (parameters.HasOptionalFields)
        {
            int position = parameters.ChromaSubsamplingX
                    && parameters.ChromaSubsamplingY
                ? (int)parameters.ChromaSamplePosition : 0;
            result += "." + (parameters.Monochrome ? "1" : "0")
                + "." + (parameters.ChromaSubsamplingX ? "1" : "0")
                + (parameters.ChromaSubsamplingY ? "1" : "0")
                + position.ToString(CultureInfo.InvariantCulture)
                + "." + FormatTwoDigits(parameters.ColorPrimaries)
                + "." + FormatTwoDigits(parameters.TransferCharacteristics)
                + "." + FormatTwoDigits(parameters.MatrixCoefficients)
                + "." + (parameters.Range == AvifRange.Full ? "1" : "0");
        }
        return result;
    }

    /// <summary>Parses the first sequence header from an AV1 OBU stream.</summary>
    /// <param name="source">An AV1 OBU stream containing a sequence header.</param>
    /// <returns>The signaled codec parameters or a model carrying the failure code.</returns>
    public Av1CodecParameters ParseSequenceHeaderParameters(
        ReadOnlySpan<byte> source)
    {
        Av1SequenceHeaderParseResult parsed =
            Av1SequenceHeaderParser.ParseObuStream(source, false, true);
        code = parsed.Code;
        if (code != AvifResultCode.Success || parsed.Header == null)
        {
            return CreateParameterFailure(code);
        }
        return CreateSequenceParameters(parsed.Header);
    }

    /// <summary>Reconciles an AV1 configuration record model with an AV1 sequence header.</summary>
    /// <param name="configuration">The configuration record fields.</param>
    /// <param name="sequenceHeaderSource">An AV1 OBU stream containing a sequence header.</param>
    /// <returns>The sequence parameters, or a model carrying NonConformingData or another failure.</returns>
    public Av1CodecParameters ReconcileConfigurationAndSequenceHeader(
        Av1CodecConfiguration configuration,
        ReadOnlySpan<byte> sequenceHeaderSource)
    {
        AvifEncodeResult encoded = CreateConfigurationBytes(configuration);
        if (encoded.GetCode() != AvifResultCode.Success)
        {
            code = encoded.GetCode();
            return CreateParameterFailure(code);
        }
        Av1ItemConfigurationParseResult parsedConfiguration =
            Av1ItemConfigurationBox.ParsePayload(encoded.GetData());
        Av1SequenceHeaderParseResult parsedSequence =
            Av1SequenceHeaderParser.ParseObuStream(
                sequenceHeaderSource,
                false,
                true);
        if (parsedSequence.Code != AvifResultCode.Success
            || parsedSequence.Header == null)
        {
            code = parsedSequence.Code;
            return CreateParameterFailure(code);
        }
        if (parsedConfiguration.Code != AvifResultCode.Success
            || parsedConfiguration.Configuration == null)
        {
            code = parsedConfiguration.Code;
            return CreateParameterFailure(code);
        }
        if (!parsedConfiguration.Configuration.MatchesSequenceHeader(
                parsedSequence.Header))
        {
            code = AvifResultCode.NonConformingData;
            return CreateParameterFailure(code);
        }
        code = AvifResultCode.Success;
        return CreateSequenceParameters(parsedSequence.Header);
    }

    /// <summary>Reconciles an RFC 6381 string, configuration record, and AV1 sequence header.</summary>
    /// <param name="codecString">The abbreviated or expanded RFC 6381 parameter.</param>
    /// <param name="configurationSource">The complete configuration record payload.</param>
    /// <param name="sequenceHeaderSource">An AV1 OBU stream containing a sequence header.</param>
    /// <returns>The reconciled sequence parameters, or a model carrying a stable failure code.</returns>
    public Av1CodecParameters ReconcileCodecSources(
        string? codecString,
        ReadOnlySpan<byte> configurationSource,
        ReadOnlySpan<byte> sequenceHeaderSource)
    {
        Av1CodecParameters stringParameters = ParseCodecString(codecString);
        if (stringParameters.Code != AvifResultCode.Success)
        {
            return stringParameters;
        }
        Av1CodecConfiguration configuration =
            ParseConfigurationRecord(configurationSource);
        if (configuration.Code != AvifResultCode.Success)
        {
            return CreateParameterFailure(configuration.Code);
        }
        Av1CodecParameters reconciled =
            ReconcileConfigurationAndSequenceHeader(
                configuration,
                sequenceHeaderSource);
        if (reconciled.Code != AvifResultCode.Success)
        {
            return reconciled;
        }
        if (!ParametersMatch(stringParameters, reconciled))
        {
            code = AvifResultCode.NonConformingData;
            return CreateParameterFailure(code);
        }
        code = AvifResultCode.Success;
        return reconciled;
    }

    AvifEncodeResult CreateConfigurationBytes(
        Av1CodecConfiguration configuration)
    {
        if (configuration == null || configuration.Code != AvifResultCode.Success
            || configuration.ConfigObus == null
            || configuration.ConfigObus.Length > int.MaxValue - 4
            || configuration.Profile < 0 || configuration.Profile > 2
            || configuration.Level < 0 || configuration.Level > 31
            || configuration.Tier < 0 || configuration.Tier > 1
            || configuration.BitDepth != 8 && configuration.BitDepth != 10
                && configuration.BitDepth != 12
            || (int)configuration.ChromaSamplePosition < 0
            || (int)configuration.ChromaSamplePosition > 2
            || configuration.InitialPresentationDelayMinusOne < 0
            || configuration.InitialPresentationDelayMinusOne > 15
            || !configuration.InitialPresentationDelayPresent
                && configuration.InitialPresentationDelayMinusOne != 0)
        {
            return new AvifEncodeResult(
                AvifResultCode.InvalidArgument,
                System.Array.Empty<byte>());
        }
        byte[] data = new byte[4 + configuration.ConfigObus.Length];
        data[0] = 129;
        data[1] = (byte)(configuration.Profile << 5 | configuration.Level);
        data[2] = (byte)(configuration.Tier << 7
            | (configuration.BitDepth > 8 ? 64 : 0)
            | (configuration.BitDepth == 12 ? 32 : 0)
            | (configuration.Monochrome ? 16 : 0)
            | (configuration.ChromaSubsamplingX ? 8 : 0)
            | (configuration.ChromaSubsamplingY ? 4 : 0)
            | (int)configuration.ChromaSamplePosition);
        data[3] = (byte)(configuration.InitialPresentationDelayPresent
            ? 16 | configuration.InitialPresentationDelayMinusOne : 0);
        configuration.ConfigObus.CopyTo(data, 4);
        Av1ItemConfigurationParseResult parsed =
            Av1ItemConfigurationBox.ParsePayload(data);
        return parsed.Code == AvifResultCode.Success
            ? new AvifEncodeResult(AvifResultCode.Success, data)
            : new AvifEncodeResult(
                parsed.Code,
                System.Array.Empty<byte>());
    }

    AvifResultCode ValidateParameters(Av1CodecParameters parameters)
    {
        if (parameters == null || parameters.Code != AvifResultCode.Success
            || parameters.SampleEntry != "av01"
            || parameters.Profile < 0 || parameters.Profile > 2
            || !Av1SequenceHeaderParser.IsValidLevel(parameters.Level)
            || parameters.Tier < 0 || parameters.Tier > 1
            || parameters.Level <= 7 && parameters.Tier != 0
            || parameters.BitDepth != 8 && parameters.BitDepth != 10
                && parameters.BitDepth != 12
            || (int)parameters.ChromaSamplePosition < 0
            || (int)parameters.ChromaSamplePosition > 2
            || parameters.ColorPrimaries < 0 || parameters.ColorPrimaries > 99
            || parameters.TransferCharacteristics < 0
            || parameters.TransferCharacteristics > 99
            || parameters.MatrixCoefficients < 0
            || parameters.MatrixCoefficients > 99
            || parameters.Range < AvifRange.Limited
            || parameters.Range > AvifRange.Full
            || !parameters.HasOptionalFields
                && !UsesAbbreviatedDefaults(parameters))
        {
            return AvifResultCode.InvalidArgument;
        }
        Av1CodecConfiguration configuration = new Av1CodecConfiguration();
        configuration.Profile = parameters.Profile;
        configuration.Level = parameters.Level;
        configuration.Tier = parameters.Tier;
        configuration.BitDepth = parameters.BitDepth;
        configuration.Monochrome = parameters.Monochrome;
        configuration.ChromaSubsamplingX = parameters.ChromaSubsamplingX;
        configuration.ChromaSubsamplingY = parameters.ChromaSubsamplingY;
        configuration.ChromaSamplePosition = parameters.ChromaSamplePosition;
        return CreateConfigurationBytes(configuration).GetCode();
    }

    bool ParametersMatch(
        Av1CodecParameters first,
        Av1CodecParameters second)
    {
        if (first.Profile != second.Profile
            || first.Level != second.Level
            || first.Tier != second.Tier
            || first.BitDepth != second.BitDepth
            || first.Monochrome != second.Monochrome
            || first.ChromaSubsamplingX != second.ChromaSubsamplingX
            || first.ChromaSubsamplingY != second.ChromaSubsamplingY
            || first.ChromaSamplePosition != second.ChromaSamplePosition)
        {
            return false;
        }
        return !first.HasOptionalFields
            || first.ColorPrimaries == second.ColorPrimaries
                && first.TransferCharacteristics
                    == second.TransferCharacteristics
                && first.MatrixCoefficients == second.MatrixCoefficients
                && first.Range == second.Range;
    }

    Av1CodecConfiguration CreatePublicConfiguration(
        ParsedAv1Configuration parsed)
    {
        Av1CodecConfiguration result = new Av1CodecConfiguration();
        result.Code = AvifResultCode.Success;
        result.Profile = parsed.GetSequenceProfile();
        result.Level = parsed.GetSequenceLevelIndex();
        result.Tier = parsed.GetSequenceTier();
        result.BitDepth = parsed.GetBitDepth();
        result.Monochrome = parsed.IsMonochrome();
        result.ChromaSubsamplingX = parsed.HasChromaSubsamplingX();
        result.ChromaSubsamplingY = parsed.HasChromaSubsamplingY();
        result.ChromaSamplePosition =
            (AvifChromaSamplePosition)parsed.GetChromaSamplePosition();
        result.InitialPresentationDelayPresent =
            parsed.HasInitialPresentationDelay();
        result.InitialPresentationDelayMinusOne =
            parsed.HasInitialPresentationDelay()
                ? parsed.GetInitialPresentationDelayMinusOne() : 0;
        result.ConfigObus = parsed.GetConfigObus();
        code = AvifResultCode.Success;
        return result;
    }

    Av1CodecParameters CreateSequenceParameters(
        ParsedAv1SequenceHeader parsed)
    {
        Av1CodecParameters result = new Av1CodecParameters();
        result.Profile = parsed.GetSequenceProfile();
        result.Level = parsed.GetSequenceLevelIndex();
        result.Tier = parsed.GetSequenceTier();
        result.BitDepth = parsed.GetBitDepth();
        result.Monochrome = parsed.IsMonochrome();
        result.ChromaSubsamplingX = parsed.HasChromaSubsamplingX();
        result.ChromaSubsamplingY = parsed.HasChromaSubsamplingY();
        result.ChromaSamplePosition =
            (AvifChromaSamplePosition)parsed.GetChromaSamplePosition();
        result.ColorPrimaries = parsed.HasColorDescription()
            ? parsed.GetColorPrimaries() : 1;
        result.TransferCharacteristics = parsed.HasColorDescription()
            ? parsed.GetTransferCharacteristics() : 1;
        result.MatrixCoefficients = parsed.HasColorDescription()
            ? parsed.GetMatrixCoefficients() : 1;
        result.Range = parsed.IsFullRange()
            ? AvifRange.Full : AvifRange.Limited;
        result.HasOptionalFields = !UsesAbbreviatedDefaults(result);
        result.Code = AvifResultCode.Success;
        code = AvifResultCode.Success;
        return result;
    }

    bool UsesAbbreviatedDefaults(Av1CodecParameters parameters)
    {
        return !parameters.Monochrome
            && parameters.ChromaSubsamplingX
            && parameters.ChromaSubsamplingY
            && parameters.ChromaSamplePosition
                == AvifChromaSamplePosition.Unknown
            && parameters.ColorPrimaries == 1
            && parameters.TransferCharacteristics == 1
            && parameters.MatrixCoefficients == 1
            && parameters.Range == AvifRange.Limited;
    }

    int ParseFixedDecimal(string value, int length)
    {
        if (value == null || value.Length != length)
        {
            return -1;
        }
        int result = 0;
        int index = 0;
        while (index < value.Length)
        {
            int digit = value[index] - '0';
            if (digit < 0 || digit > 9)
            {
                return -1;
            }
            result = result * 10 + digit;
            index++;
        }
        return result;
    }

    string FormatTwoDigits(int value)
    {
        return value < 10
            ? "0" + value.ToString(CultureInfo.InvariantCulture)
            : value.ToString(CultureInfo.InvariantCulture);
    }

    Av1CodecConfiguration CreateConfigurationFailure(AvifResultCode failure)
    {
        Av1CodecConfiguration result = new Av1CodecConfiguration();
        result.Code = failure;
        return result;
    }

    Av1CodecParameters CreateParameterFailure(AvifResultCode failure)
    {
        Av1CodecParameters result = new Av1CodecParameters();
        return SetParameterFailure(result, failure);
    }

    Av1CodecParameters SetParameterFailure(
        Av1CodecParameters result,
        AvifResultCode failure)
    {
        result.Code = failure;
        code = failure;
        return result;
    }
}
