using System;

namespace avif;

/// <summary>Defines AV1 configuration-record, RFC 6381, and sequence-header parameter operations.</summary>
public interface IAv1CodecConfigurationCodec
{
    /// <summary>Returns the outcome of the most recent operation.</summary>
    /// <returns>The stable result code.</returns>
    AvifResultCode GetCode();

    /// <summary>Parses an AV1 codec configuration record payload without its ISO box header.</summary>
    /// <param name="source">The complete record beginning with marker and version fields.</param>
    /// <returns>The parsed configuration or a model carrying the failure code.</returns>
    Av1CodecConfiguration ParseConfigurationRecord(ReadOnlySpan<byte> source);

    /// <summary>Generates an AV1 codec configuration record payload without an ISO box header.</summary>
    /// <param name="configuration">The configuration fields and optional configuration OBUs.</param>
    /// <returns>The generated bytes or a stable failure result.</returns>
    AvifEncodeResult GenerateConfigurationRecord(
        Av1CodecConfiguration configuration);

    /// <summary>Parses an AV1 RFC 6381 codecs parameter string.</summary>
    /// <param name="source">The complete abbreviated or expanded codecs parameter.</param>
    /// <returns>The parsed parameters or a model carrying the failure code.</returns>
    Av1CodecParameters ParseCodecString(string? source);

    /// <summary>Generates an abbreviated or expanded AV1 RFC 6381 codecs parameter string.</summary>
    /// <param name="parameters">The parameters to validate and serialize.</param>
    /// <returns>The codec string, or an empty string on failure.</returns>
    string GenerateCodecString(Av1CodecParameters parameters);

    /// <summary>Parses the first sequence header from an AV1 OBU stream.</summary>
    /// <param name="source">An AV1 OBU stream containing a sequence header.</param>
    /// <returns>The signaled codec parameters or a model carrying the failure code.</returns>
    Av1CodecParameters ParseSequenceHeaderParameters(
        ReadOnlySpan<byte> source);

    /// <summary>Reconciles an AV1 configuration record model with an AV1 sequence header.</summary>
    /// <param name="configuration">The configuration record fields.</param>
    /// <param name="sequenceHeaderSource">An AV1 OBU stream containing a sequence header.</param>
    /// <returns>The sequence parameters, or a model carrying NonConformingData or another failure.</returns>
    Av1CodecParameters ReconcileConfigurationAndSequenceHeader(
        Av1CodecConfiguration configuration,
        ReadOnlySpan<byte> sequenceHeaderSource);

    /// <summary>Reconciles an RFC 6381 string, configuration record, and AV1 sequence header.</summary>
    /// <param name="codecString">The abbreviated or expanded RFC 6381 parameter.</param>
    /// <param name="configurationSource">The complete configuration record payload.</param>
    /// <param name="sequenceHeaderSource">An AV1 OBU stream containing a sequence header.</param>
    /// <returns>The reconciled sequence parameters, or a model carrying a stable failure code.</returns>
    Av1CodecParameters ReconcileCodecSources(
        string? codecString,
        ReadOnlySpan<byte> configurationSource,
        ReadOnlySpan<byte> sequenceHeaderSource);
}
