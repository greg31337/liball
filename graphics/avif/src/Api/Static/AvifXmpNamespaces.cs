namespace avif;

/// <summary>Defines the standard namespace identifiers used by AVIF XMP metadata.</summary>
public static class AvifXmpNamespaces
{
    /// <summary>The RDF syntax namespace.</summary>
    public const string Rdf = "http://www.w3.org/1999/02/22-rdf-syntax-ns#";

    /// <summary>The Dublin Core elements namespace.</summary>
    public const string DublinCore = "http://purl.org/dc/elements/1.1/";

    /// <summary>The Adobe XMP namespace.</summary>
    public const string Xmp = "http://ns.adobe.com/xap/1.0/";

    /// <summary>The TIFF metadata namespace.</summary>
    public const string Tiff = "http://ns.adobe.com/tiff/1.0/";

    /// <summary>The Exif metadata namespace.</summary>
    public const string Exif = "http://ns.adobe.com/exif/1.0/";
}
