namespace molecule;


/// <summary>
/// Defines the supported values for double bond configuration.
/// </summary>
public enum DoubleBondConfiguration
{
    /// <summary>
    /// Specifies none.
    /// </summary>
    None = 0,
    /// <summary>
    /// Specifies e.
    /// </summary>
    E = 1,
    /// <summary>
    /// Specifies z.
    /// </summary>
    Z = 2,
    /// <summary>
    /// Specifies cis.
    /// </summary>
    Cis = 3,
    /// <summary>
    /// Specifies trans.
    /// </summary>
    Trans = 4,
    /// <summary>
    /// Specifies unspecified.
    /// </summary>
    Unspecified = 5,
    /// <summary>
    /// Specifies unknown.
    /// </summary>
    Unknown = 6
}

