namespace molecule;


/// <summary>
/// Defines the supported values for aromaticity.
/// </summary>
public enum Aromaticity
{
    /// <summary>
    /// Specifies unknown.
    /// </summary>
    Unknown = 0,
    /// <summary>
    /// Specifies non aromatic.
    /// </summary>
    NonAromatic = 1,
    /// <summary>
    /// Specifies aromatic.
    /// </summary>
    Aromatic = 2,
    /// <summary>
    /// Specifies candidate.
    /// </summary>
    Candidate = 3
}

