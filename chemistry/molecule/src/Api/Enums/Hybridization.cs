namespace molecule;


/// <summary>
/// Defines the supported values for hybridization.
/// </summary>
public enum Hybridization
{
    /// <summary>
    /// Specifies unknown.
    /// </summary>
    Unknown = 0,
    /// <summary>
    /// Specifies s.
    /// </summary>
    S = 1,
    /// <summary>
    /// Specifies sp.
    /// </summary>
    Sp = 2,
    /// <summary>
    /// Specifies sp 2.
    /// </summary>
    Sp2 = 3,
    /// <summary>
    /// Specifies sp 3.
    /// </summary>
    Sp3 = 4,
    /// <summary>
    /// Specifies sp 3d.
    /// </summary>
    Sp3d = 5,
    /// <summary>
    /// Specifies sp 3d 2.
    /// </summary>
    Sp3d2 = 6
}

