namespace molecule;


/// <summary>
/// Defines the supported values for chirality.
/// </summary>
public enum Chirality
{
    /// <summary>
    /// Specifies none.
    /// </summary>
    None = 0,
    /// <summary>
    /// Specifies clockwise.
    /// </summary>
    Clockwise = 1,
    /// <summary>
    /// Specifies counter clockwise.
    /// </summary>
    CounterClockwise = 2,
    /// <summary>
    /// Specifies unspecified.
    /// </summary>
    Unspecified = 3,
    /// <summary>
    /// Specifies unknown.
    /// </summary>
    Unknown = 4
}

