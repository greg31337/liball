namespace molecule;


/// <summary>
/// Defines the supported values for error severity.
/// </summary>
public enum ErrorSeverity
{
    /// <summary>
    /// Specifies info.
    /// </summary>
    Info = 0,
    /// <summary>
    /// Specifies warning.
    /// </summary>
    Warning = 1,
    /// <summary>
    /// Specifies error.
    /// </summary>
    Error = 2,
    /// <summary>
    /// Specifies fatal.
    /// </summary>
    Fatal = 3
}

