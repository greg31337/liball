namespace molecule;


/// <summary>
/// Defines the supported values for bond order.
/// </summary>
public enum BondOrder
{
    /// <summary>
    /// Specifies unknown.
    /// </summary>
    Unknown = 0,
    /// <summary>
    /// Specifies none.
    /// </summary>
    None = 1,
    /// <summary>
    /// Specifies single.
    /// </summary>
    Single = 2,
    /// <summary>
    /// Specifies double.
    /// </summary>
    Double = 3,
    /// <summary>
    /// Specifies triple.
    /// </summary>
    Triple = 4,
    /// <summary>
    /// Specifies quadruple.
    /// </summary>
    Quadruple = 5,
    /// <summary>
    /// Specifies aromatic.
    /// </summary>
    Aromatic = 6,
    /// <summary>
    /// Specifies dative.
    /// </summary>
    Dative = 7
}

