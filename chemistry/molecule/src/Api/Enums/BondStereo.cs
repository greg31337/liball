namespace molecule;


/// <summary>
/// Defines the supported values for bond stereo.
/// </summary>
public enum BondStereo
{
    /// <summary>
    /// Specifies none.
    /// </summary>
    None = 0,
    /// <summary>
    /// Specifies wedge.
    /// </summary>
    Wedge = 1,
    /// <summary>
    /// Specifies hash.
    /// </summary>
    Hash = 2,
    /// <summary>
    /// Specifies up or down.
    /// </summary>
    UpOrDown = 3,
    /// <summary>
    /// Specifies cis.
    /// </summary>
    Cis = 4,
    /// <summary>
    /// Specifies trans.
    /// </summary>
    Trans = 5,
    /// <summary>
    /// Specifies e.
    /// </summary>
    E = 6,
    /// <summary>
    /// Specifies z.
    /// </summary>
    Z = 7,
    /// <summary>
    /// Specifies unknown.
    /// </summary>
    Unknown = 8
}

