namespace molecule;


/// <summary>
/// Defines the supported values for radical state.
/// </summary>
public enum RadicalState
{
    /// <summary>
    /// Specifies none.
    /// </summary>
    None = 0,
    /// <summary>
    /// Specifies singlet.
    /// </summary>
    Singlet = 1,
    /// <summary>
    /// Specifies doublet.
    /// </summary>
    Doublet = 2,
    /// <summary>
    /// Specifies triplet.
    /// </summary>
    Triplet = 3,
    /// <summary>
    /// Specifies quartet.
    /// </summary>
    Quartet = 4
}

