namespace molecule;


/// <summary>
/// Defines the supported values for standardization policy.
/// </summary>
public enum StandardizationPolicy
{
    /// <summary>
    /// Specifies none.
    /// </summary>
    None = 0,
    /// <summary>
    /// Specifies preserve.
    /// </summary>
    Preserve = 1,
    /// <summary>
    /// Specifies normalize.
    /// </summary>
    Normalize = 2,
    /// <summary>
    /// Specifies strict.
    /// </summary>
    Strict = 3,
    /// <summary>
    /// Specifies relaxed.
    /// </summary>
    Relaxed = 4
}

