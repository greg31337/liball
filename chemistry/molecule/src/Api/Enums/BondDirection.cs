namespace molecule;


/// <summary>
/// Defines the supported values for bond direction.
/// </summary>
public enum BondDirection
{
    /// <summary>
    /// Specifies none.
    /// </summary>
    None = 0,
    /// <summary>
    /// Specifies up.
    /// </summary>
    Up = 1,
    /// <summary>
    /// Specifies down.
    /// </summary>
    Down = 2,
    /// <summary>
    /// Specifies either.
    /// </summary>
    Either = 3,
    /// <summary>
    /// Specifies crossed.
    /// </summary>
    Crossed = 4
}

