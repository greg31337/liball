namespace iso20022;

/// <summary>Contains media types used by supported ISO 20022 artifacts.</summary>
public static class Iso20022MediaTypes
{
    /// <summary>The XML media type.</summary>
    public const string Xml = "application/xml";
    /// <summary>The XML Schema media type.</summary>
    public const string XmlSchema = "application/xml";
    /// <summary>The JSON media type.</summary>
    public const string Json = "application/json";
    /// <summary>The JSON Schema media type.</summary>
    public const string JsonSchema = "application/schema+json";
    /// <summary>The C# source media type.</summary>
    public const string CSharp = "text/x-csharp";
    /// <summary>The ZIP archive media type.</summary>
    public const string Zip = "application/zip";
    /// <summary>The Office Open XML workbook media type.</summary>
    public const string OpenXmlWorkbook = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";
}
