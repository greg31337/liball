namespace sql;

/// <summary>Specifies the supported diagnostic severity.</summary>
public enum SqlDiagnosticSeverity
{
    /// <summary>Represents hidden.</summary>
    Hidden = 0,
    /// <summary>Represents info.</summary>
    Info = 1,
    /// <summary>Represents warning.</summary>
    Warning = 2,
    /// <summary>Represents error.</summary>
    Error = 3
}
