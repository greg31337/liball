using System;

namespace random;

/// <summary>
/// Generates separated points in the open upper boundary of a unit hypercube.
/// </summary>
/// <remarks>
/// Points are constructed by bounded sequential dart throwing. The first point is
/// accepted immediately. Each later point receives an independent candidate budget;
/// exhaustion never substitutes a too-close candidate. The sampler retains the
/// supplied mutable generator and is not safe for concurrent use without external
/// synchronization.
/// </remarks>
public class PoissonDiskSampler : IPoissonDiskSampler
{
    IRandomSource generator;
    int dimension;
    double minimumDistance;
    double minimumDistanceSquared;
    int maximumAttemptsPerPoint;
    int lastAcceptedPointCount;
    long lastAttemptCount;
    long totalAttemptCount;

    /// <summary>
    /// Creates a bounded Poisson-disk sampler in a unit hypercube.
    /// </summary>
    /// <param name="generator">The generator used for candidate coordinates.</param>
    /// <param name="dimension">The positive point dimension.</param>
    /// <param name="minimumDistance">The finite positive Euclidean separation.</param>
    /// <param name="maximumAttemptsPerPoint">The positive candidate budget for each requested point.</param>
    /// <exception cref="RandomArgumentException">An argument is null, non-finite, or outside its required positive range.</exception>
    public PoissonDiskSampler(IRandomSource generator, int dimension, double minimumDistance, int maximumAttemptsPerPoint)
    {
        Guard.NotNull(generator, "generator");
        Guard.PositiveCount(dimension, "dimension");
        Guard.Finite(minimumDistance, "minimumDistance");
        if (minimumDistance <= 0.0)
        {
            throw RandomArgumentException.Create("minimumDistance", "The minimum distance must be positive.");
        }

        Guard.PositiveCount(maximumAttemptsPerPoint, "maximumAttemptsPerPoint");
        this.generator = generator;
        this.dimension = dimension;
        this.minimumDistance = minimumDistance;
        minimumDistanceSquared = minimumDistance * minimumDistance;
        this.maximumAttemptsPerPoint = maximumAttemptsPerPoint;
        lastAcceptedPointCount = 0;
        lastAttemptCount = 0L;
        totalAttemptCount = 0L;
    }

    /// <summary>
    /// Returns the number of coordinates in each point.
    /// </summary>
    /// <returns>The positive point dimension.</returns>
    public int Dimension()
    {
        return dimension;
    }

    /// <summary>
    /// Returns the required Euclidean separation.
    /// </summary>
    /// <returns>The finite positive minimum distance.</returns>
    public double MinimumDistance()
    {
        return minimumDistance;
    }

    /// <summary>
    /// Returns the per-point candidate budget.
    /// </summary>
    /// <returns>The positive maximum candidate count for each point.</returns>
    public int MaximumAttemptsPerPoint()
    {
        return maximumAttemptsPerPoint;
    }

    /// <summary>
    /// Returns the number of points accepted by the latest valid sample request.
    /// </summary>
    /// <returns>The accepted count at success or exhaustion.</returns>
    public int LastAcceptedPointCount()
    {
        return lastAcceptedPointCount;
    }

    /// <summary>
    /// Returns the number of candidates generated by the latest valid sample request.
    /// </summary>
    /// <returns>The attempt count at success or exhaustion.</returns>
    public long LastAttemptCount()
    {
        return lastAttemptCount;
    }

    /// <summary>
    /// Returns the cumulative candidate count across valid requests.
    /// </summary>
    /// <returns>The cumulative count, saturated at <c>long.MaxValue</c>.</returns>
    public long TotalAttemptCount()
    {
        return totalAttemptCount;
    }

    /// <summary>
    /// Returns a bounded Poisson-disk point design.
    /// </summary>
    /// <param name="pointCount">The positive number of requested points.</param>
    /// <returns>A new point-major array containing the separated points.</returns>
    /// <exception cref="RandomArgumentException">The point count or required storage is invalid.</exception>
    /// <exception cref="RandomExhaustedException">A point cannot be placed within its candidate budget.</exception>
    public double[] Sample(int pointCount)
    {
        int requiredLength = RequiredOutputLength(pointCount);
        double[] result = new double[requiredLength];
        SampleInto(pointCount, result);
        return result;
    }

    /// <summary>
    /// Writes a bounded Poisson-disk point design.
    /// </summary>
    /// <param name="pointCount">The positive number of requested points.</param>
    /// <param name="destination">The exact point-major destination.</param>
    /// <remarks>
    /// On exhaustion, the first <see cref="LastAcceptedPointCount()"/> points remain
    /// written and the remaining destination entries retain their prior values.
    /// </remarks>
    /// <exception cref="RandomArgumentException">The point count or destination is invalid.</exception>
    /// <exception cref="RandomExhaustedException">A point cannot be placed within its candidate budget.</exception>
    public void SampleInto(int pointCount, Span<double> destination)
    {
        int requiredLength = RequiredOutputLength(pointCount);
        Guard.ExactSpanLength(destination.Length, requiredLength, "destination");
        lastAcceptedPointCount = 0;
        lastAttemptCount = 0L;
        double[] candidate = new double[dimension];
        while (lastAcceptedPointCount < pointCount)
        {
            int pointAttemptCount = 0;
            bool accepted = false;
            while (pointAttemptCount < maximumAttemptsPerPoint)
            {
                pointAttemptCount++;
                RecordAttempt();
                FillCandidate(candidate);
                if (IsSeparated(candidate, destination, lastAcceptedPointCount))
                {
                    accepted = true;
                    break;
                }
            }

            if (!accepted)
            {
                throw RandomExhaustedException.Create($"The Poisson-disk sampler placed {lastAcceptedPointCount} of {pointCount} points before exhausting the candidate budget for the next point after {lastAttemptCount} total attempts.");
            }

            WriteCandidate(candidate, destination, lastAcceptedPointCount);
            lastAcceptedPointCount++;
        }
    }

    /// <summary>
    /// Returns the required point-major storage length for a design.
    /// </summary>
    /// <param name="pointCount">The positive number of points.</param>
    /// <returns>The point count multiplied by the dimension.</returns>
    /// <exception cref="RandomArgumentException">The point count is not positive or required storage exceeds <c>int.MaxValue</c>.</exception>
    public int RequiredOutputLength(int pointCount)
    {
        Guard.PositiveCount(pointCount, "pointCount");
        if (pointCount > int.MaxValue / dimension)
        {
            throw RandomArgumentException.Create("pointCount", "The requested design contains too many coordinates.");
        }

        return pointCount * dimension;
    }

    void RecordAttempt()
    {
        if (lastAttemptCount < long.MaxValue)
        {
            lastAttemptCount++;
        }

        if (totalAttemptCount < long.MaxValue)
        {
            totalAttemptCount++;
        }
    }

    void FillCandidate(double[] candidate)
    {
        int coordinate = 0;
        while (coordinate < dimension)
        {
            candidate[coordinate] = FloatingUniform.NextDoubleClosedOpen(generator);
            coordinate++;
        }
    }

    bool IsSeparated(double[] candidate, Span<double> destination, int acceptedPointCount)
    {
        int point = 0;
        while (point < acceptedPointCount)
        {
            double distanceSquared = 0.0;
            int coordinate = 0;
            while (coordinate < dimension)
            {
                double delta = candidate[coordinate] - destination[point * dimension + coordinate];
                distanceSquared += delta * delta;
                coordinate++;
            }

            if (distanceSquared < minimumDistanceSquared)
            {
                return false;
            }

            point++;
        }

        return true;
    }

    void WriteCandidate(double[] candidate, Span<double> destination, int point)
    {
        int coordinate = 0;
        while (coordinate < dimension)
        {
            destination[point * dimension + coordinate] = candidate[coordinate];
            coordinate++;
        }
    }
}
