namespace htmlgui;

/// <summary>Provides stable class and attribute tokens for accessibility support hooks.</summary>
public static class AccessibilityHooks
{
    /// <summary>The forced-colors and high-contrast class token.</summary>
    public const string ForcedColorsClass = "htmlgui-forced-colors";
    /// <summary>The browser-zoom class token.</summary>
    public const string ZoomClass = "htmlgui-zoom";
    /// <summary>The narrow-viewport reflow class token.</summary>
    public const string ReflowClass = "htmlgui-reflow";
    /// <summary>The focus-visible class token.</summary>
    public const string FocusVisibleClass = "htmlgui-focus-visible";
    /// <summary>The minimum-target-size class token.</summary>
    public const string TargetSizeClass = "htmlgui-target-size";
    /// <summary>The reduced-motion class token.</summary>
    public const string ReducedMotionClass = "htmlgui-reduced-motion";
    /// <summary>The reduced-transparency class token.</summary>
    public const string ReducedTransparencyClass = "htmlgui-reduced-transparency";
    /// <summary>The screen-reader-only class token.</summary>
    public const string ScreenReaderOnlyClass = "htmlgui-screen-reader-only";
    /// <summary>The non-color status class token.</summary>
    public const string NonColorStatusClass = "htmlgui-non-color-status";
    /// <summary>The textual non-color status child class token.</summary>
    public const string StatusTextClass = "htmlgui-status-text";
    /// <summary>The minimum target-size data attribute.</summary>
    public const string TargetSizeAttribute = "data-htmlgui-target-size";
}
